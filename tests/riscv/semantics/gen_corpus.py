#!/usr/bin/env python3
"""
Generate tests/riscv/semantics/corpus/{rv,rv64,rv32}_gen_*.s: the scalar corpus of the semantics tests.

The lines are the ones of the decoder corpus (tests/riscv/corpus/rv32|rv64/*.s, generated by
tests/riscv/tools/gen_corpus.py from the instruction list): every instruction with every register of
each operand (the zero register, the same register in several operands included), the edge values of
the immediates, every rounding mode, the aq / rl bits, the fence sets. This script

  * leaves out what the semantics tests don't run: the privileged instructions (user mode can't run
    them), the pseudo instructions which need a symbol, the vector extension, the CSRs which aren't
    in user mode or in the description (the counters differ from run to run);
  * keeps only the lines llvm-mc assembles (the decoder corpus has lines LLVM rejects on purpose);
  * puts the lines which are the same text in RV32 and RV64 into rv_gen_<extension>.s (run for both) and
    the others into rv64_gen_<extension>.s / rv32_gen_<extension>.s;
  * runs the Zicfilp / Zicfiss lines in both modes: the instructions are Zimop / Zcmop instructions
    until the supervisor enables the control flow integrity (`@mode: cfi`).

  python3 tests/riscv/semantics/gen_corpus.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import rvasm

REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
SOURCE = os.path.join(REPO, 'tests', 'riscv', 'corpus')
OUT = os.path.join(HERE, 'corpus')

# The decoder corpus files which are not run
SKIP_FILES = {'privileged', 'pseudo'}
# The CSRs of the description (user mode), by name and number
USER_CSRS = {'fflags': 1, 'frm': 2, 'fcsr': 3, 'vstart': 8, 'vxsat': 9, 'vxrm': 10, 'vcsr': 15, 'vl': 0xc20,
             'vtype': 0xc21, 'vlenb': 0xc22, 'ssp': 0x011}
CSR_NUMBERS = set(USER_CSRS.values())
# The Zicsr lines which are not a CSR operand: the fixed pseudo instructions
FIXED_CSR = {'frcsr', 'fscsr', 'frrm', 'fsrm', 'fsrmi', 'frflags', 'fsflags', 'fsflagsi', 'unimp'}
# The mnemonics which Zicfilp / Zicfiss change when they are enabled
CFI = re.compile(r'^(lpad|sspush|sspopchk|ssrdp|ssamoswap\.\w+|c\.sspush|c\.sspopchk)\b')


def split_line(raw):
    m = re.search(r'(#|//)', raw)
    if not m:
        return raw.strip(), ''
    return raw[:m.start()].strip(), raw[m.end():].strip()


def csr_ok(text):
    """True if the Zicsr line is for a CSR of user mode which the description has."""
    mnemonic = text.split()[0]
    if mnemonic in FIXED_CSR:
        return True
    if not mnemonic.startswith('csr'):
        return True
    ops = [o.strip() for o in text[len(mnemonic):].split(',')]
    # csrr rd, csr / csrrw rd, csr, rs1 / csrw csr, rs1 / csrrwi rd, csr, uimm
    index = 1 if mnemonic in ('csrr', 'csrrw', 'csrrs', 'csrrc', 'csrrwi', 'csrrsi', 'csrrci') else 0
    csr = ops[index]
    if csr in USER_CSRS:
        return True
    try:
        return int(csr, 0) in CSR_NUMBERS
    except ValueError:
        return False


def is_inside_jump(text):
    """True for a jump or a branch whose target is its own address (an endless loop if it is taken) or, for the
    4 byte ones, the middle of the instruction: the reference processors would execute the second half of
    the instruction as a compressed one."""
    m = re.match(r'(c\.)?(j|jal|b\w+)\s+(.*?),?\s*(-?\d+)$', text)
    if not m:
        return False
    offset = int(m.group(4))
    if m.group(1):
        return offset == 0
    return offset in (0, 2)


def read_lines(xlen):
    """{file: [(text, features)]} of the decoder corpus of RV`xlen`."""
    directory = os.path.join(SOURCE, 'rv%d' % xlen)
    files = {}
    for name in sorted(os.listdir(directory)):
        stem = name[:-2]
        if stem in SKIP_FILES or name[-2:] != '.s':
            continue
        lines = []
        with open(os.path.join(directory, name)) as f:
            for raw in f:
                raw = raw.rstrip('\n')
                if not raw.strip() or raw.lstrip().startswith('#'):
                    continue
                text, comment = split_line(raw)
                if not text:
                    continue
                if stem == 'zicsr' and not csr_ok(text):
                    continue
                if is_inside_jump(text):
                    continue
                lines.append((text, comment))
        files[stem] = lines
    return files


def line_tags(text, comment, cfi):
    tags = [comment] if comment else []
    if cfi:
        tags.append('@mode: cfi')
    return '  # ' + ' '.join(tags) if tags else ''


def assembled(xlen, texts):
    """The set of the texts llvm-mc assembles for RV`xlen`."""
    ok = set()
    uniq = sorted(set(texts))
    for text, (blob, error) in zip(uniq, rvasm.assemble(xlen, uniq)):
        if error is None and blob:
            ok.add(text)
    return ok


def main():
    sources = {32: read_lines(32), 64: read_lines(64)}
    ok = {}
    for xlen in (32, 64):
        texts = [t for lines in sources[xlen].values() for t, _ in lines]
        ok[xlen] = assembled(xlen, texts)
        print('rv%d: %d lines, %d assemble' % (xlen, len(set(texts)), len(ok[xlen])))

    for name in os.listdir(OUT):
        if '_gen_' in name:
            os.unlink(os.path.join(OUT, name))

    total = 0
    for stem in sorted(set(sources[32]) | set(sources[64])):
        common, only = [], {32: [], 64: []}
        seen = {32: set(), 64: set()}
        lines64 = [(t, c) for t, c in sources[64].get(stem, []) if t in ok[64]]
        lines32 = [(t, c) for t, c in sources[32].get(stem, []) if t in ok[32]]
        texts32 = {t for t, _ in lines32}
        texts64 = {t for t, _ in lines64}
        for xlen, lines, other in ((64, lines64, texts32), (32, lines32, texts64)):
            for text, comment in lines:
                if text in seen[xlen]:
                    continue
                seen[xlen].add(text)
                if text in other:
                    if xlen == 64:
                        common.append((text, comment))
                else:
                    only[xlen].append((text, comment))
        for prefix, lines in (('rv', common), ('rv64', only[64]), ('rv32', only[32])):
            if not lines:
                continue
            path = os.path.join(OUT, '%s_gen_%s.s' % (prefix, stem))
            with open(path, 'w') as f:
                f.write('# GENERATED by tests/riscv/semantics/gen_corpus.py from tests/riscv/corpus: do not edit\n')
                for text, comment in lines:
                    if CFI.match(text) or (stem == 'zicsr' and re.search(r'\bssp\b|\b0x011\b|\b17\b', text)):
                        f.write(text + line_tags(text, comment, False) + '\n')
                        f.write(text + line_tags(text, comment, True) + '\n')
                        total += 2
                    else:
                        f.write(text + line_tags(text, comment, False) + '\n')
                        total += 1
    print('%d lines in corpus' % total)


if __name__ == '__main__':
    main()
