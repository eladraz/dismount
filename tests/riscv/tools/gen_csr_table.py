#!/usr/bin/env python3
"""Generate Source/dismount/proc/riscv/RiscvCsrNames.cpp: the CSR names which
LLVM prints (llvm-objdump, every number of 0..4095, RV32 and RV64) and the
alternative names it only reads (llvm-mc). LLVM 23 doesn't gate the names by
feature (a name is printed whichever features are enabled), so every entry is
FEAT_I; the names of the RV32 only CSRs (the h halves) are flagged.

  python3 tests/riscv/tools/gen_csr_table.py
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rvlib

# The names llvm-mc reads and llvm-objdump never prints
ALTERNATIVES = [('sbadaddr', 0x143), ('mbadaddr', 0x343), ('sptbr', 0x180), ('dscratch', 0x7b2)]


def names(bits):
    data = b''.join(struct.pack('<I', 0x00002573 | (n << 20)) for n in range(4096))
    result = rvlib.objdump_bytes(data, bits, rvlib.all_features(bits) + rvlib.VECTOR_FEATURES,
                                 ['-M', 'no-aliases'])
    assert len(result) == 4096
    out = []
    for _, _, text in result:
        name = text.replace(',', ' ').split()[2]
        out.append(None if name.isdigit() else name)
    return out


def main():
    n32 = names(32)
    n64 = names(64)
    rows = []
    for n in range(4096):
        if n32[n] is not None and n64[n] is not None:
            assert n32[n] == n64[n], (n, n32[n], n64[n])
            rows.append((n, n32[n], False))
        elif n32[n] is not None:
            rows.append((n, n32[n], True))
        elif n64[n] is not None:
            raise RuntimeError('RV64 only CSR %x' % n)
    path = os.path.join(rvlib.REPO, 'Source', 'dismount', 'proc', 'riscv', 'RiscvCsrNames.cpp')
    with open(path, 'w') as f:
        f.write('''#include "dismount/dismount.h"
/*
 * RiscvCsrNames.cpp
 *
 * The CSR names of LLVM 23 (see RiscvOperandCodec.h).
 *
 * GENERATED by tests/riscv/tools/gen_csr_table.py from llvm-objdump: edit the
 * generator, not this file. LLVM doesn't gate the names by feature, so every
 * name is FEAT_I.
 *
 * Author: Elad Raz <e@eladraz.com>
 */
#include "xStl/types.h"
#include "dismount/proc/riscv/RiscvOperandCodec.h"

namespace riscvdis {

#define CSR(name, number, flags) { name, number, RiscvFeatures::FEAT_I, flags }

const RiscvCsrName gRiscvCsrNames[] = {
''')
        for n, name, rv32 in rows:
            f.write('    CSR("%s", 0x%03x, %s),\n' % (name, n, 'RISCV_CSR_RV32_ONLY' if rv32 else '0'))
        f.write('    // The alternative names\n')
        for name, n in ALTERNATIVES:
            f.write('    CSR("%s", 0x%03x, RISCV_CSR_ALTERNATIVE),\n' % (name, n))
        f.write('''    { NULL, 0, 0, 0 }
};

#undef CSR

} // namespace riscvdis
''')
    print('%d names (%d RV32 only) -> %s' % (len(rows), sum(1 for r in rows if r[2]), path))


if __name__ == '__main__':
    main()
