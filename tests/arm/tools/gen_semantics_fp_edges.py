#!/usr/bin/env python3
"""Write tests/arm/semantics/corpus/a64_fp.s: the lines of a64_fp_all.s (up to a few per mnemonic and shape of
operands) with directed states (`// @state:`) whose floating point lanes are the special values (quiet and
signaling NaNs of both signs, infinities, zeros, denormals, the smallest and largest normal numbers, the powers of
two of the conversions) and whose FPCR is every combination of the rounding mode, FZ, DN and FZ16 (and the
cumulative flags FPSR already set). They reach the NaN propagation, the default NaN, the flush to zero and the
exception flags which random lanes rarely do.

    gen_semantics_fp_edges.py [--states N]
"""
import argparse
import collections
import os
import random
import re
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import armlib
import check_armfp as C

CORPUS = os.path.join(armlib.REPO, 'tests', 'arm', 'semantics', 'corpus')
SOURCE = os.path.join(CORPUS, 'a64_fp_all.s')
OUTPUT = os.path.join(CORPUS, 'a64_fp.s')


def shape_of(text):
    parts = text.split(None, 1)
    ops = parts[1] if len(parts) > 1 else ''
    ops = re.sub(r'\b([vqdshbxwz])\d+\b', r'\1#', ops)
    ops = re.sub(r'#-?(0x)?[0-9a-fA-F.]+', '#N', ops)
    ops = re.sub(r'\[\d+\]', '[i]', ops)
    return parts[0].lower() + ' ' + ops


def element_bits(operand):
    """The size of the floating point elements of a register operand text."""
    m = re.match(r'^v\d+\.(\d*)([bhsd])', operand)
    if m:
        return {'b': 8, 'h': 16, 's': 32, 'd': 64}[m.group(2)]
    m = re.match(r'^([bhsdq])\d+$', operand)
    if m:
        return {'b': 8, 'h': 16, 's': 32, 'd': 64, 'q': 128}[m.group(1)]
    m = re.match(r'^v\d+\.([bhsd])\[', operand)
    if m:
        return {'b': 8, 'h': 16, 's': 32, 'd': 64}[m.group(1)]
    return 0


def lane_value(rng, bits):
    if bits in (16, 32, 64):
        return C.draw(rng, bits)
    return rng.getrandbits(bits)


FPCRS = [0x0, 0x400000, 0x800000, 0xc00000, 0x1000000, 0x2000000, 0x3000000, 0x80000, 0x1080000, 0x2080000,
         0x1400000, 0x2c00000, 0x3c80000]


def states_of(text, rng, count):
    operands = [o.strip() for o in re.split(r',\s*(?![^{]*\})', text.split(None, 1)[1])] if ' ' in text else []
    registers = []
    for o in operands:
        m = re.match(r'^[vqdshb](\d+)', o)
        if m:
            registers.append((int(m.group(1)), element_bits(o), o))
    out = []
    for n in range(count):
        tokens = []
        used = {}
        for number, bits, operand in registers:
            if bits not in (16, 32, 64):
                continue
            # the lanes of the 128 bit register
            lanes = 128 // bits
            value = 0
            common = lane_value(rng, bits) if rng.random() < 0.3 else None
            for l in range(lanes):
                x = common if (common is not None and rng.random() < 0.5) else lane_value(rng, bits)
                value |= x << (l * bits)
            used[number] = value
        for number, value in used.items():
            tokens.append('v%d=%x' % (number, value))
        tokens.append('fpcr=%x' % rng.choice(FPCRS))
        if rng.random() < 0.3:
            tokens.append('fpsr=%x' % rng.choice([0x10, 0x1f, 0x8000080, 0x9f]))
        out.append('@state: ' + ' '.join(tokens))
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--states', type=int, default=6)
    parser.add_argument('--per-shape', type=int, default=2)
    args = parser.parse_args()
    seen = collections.Counter()
    out = ['// Generated by tests/arm/tools/gen_semantics_fp_edges.py: do not edit.',
           '// The lines of a64_fp_all.s with directed states of special floating point values and FPCR modes.', '']
    count = 0
    for raw in open(SOURCE):
        if raw.startswith('//') or not raw.strip():
            continue
        m = re.match(r'^(.*?)\s*//\s*@feature:\s*(\S+)\s*$', raw.rstrip('\n'))
        text = (m.group(1) if m else raw.split('//')[0]).strip()
        if not text:
            continue
        shape = shape_of(text)
        if seen[shape] >= args.per_shape:
            continue
        seen[shape] += 1
        rng = random.Random(zlib.crc32(text.encode()))
        states = states_of(text, rng, args.states)
        out.append('%s   // %s' % (text, '  '.join(states)))
        count += 1
    open(OUTPUT, 'w').write('\n'.join(out) + '\n')
    print('%d lines' % count)


if __name__ == '__main__':
    main()
