#!/usr/bin/env python3
"""Write Source/dismount/proc/arm/Arm64SemanticTableSimd.cpp, the semantic table of the A64
scalar floating point, Advanced SIMD and cryptographic instructions (gArm64SimdSemanticTable):
one entry per mnemonic of gArm64SimdEncodingTable which the lifter (Arm64SemanticLiftSimd*.cpp,
Arm64SemanticLiftFloat.cpp, Arm64SemanticLiftCrypto.cpp) lifts, with the classification of the
mnemonic (category, units, properties, flags).

The mnemonics which are not lifted are not in the table: they are lifted to OP_UNDEFINED and
classified as CATEGORY_UNKNOWN, and ArmFeatures::getSupport() of their feature has no
SUPPORT_LIFT (see UNLIFTED below for the reason of each group).

    gen_a64_simd_semantic_table.py          # rewrite the table
    gen_a64_simd_semantic_table.py --check  # exit 1 if the file differs
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import armlib

TABLE = os.path.join(armlib.REPO, 'Source', 'dismount', 'proc', 'arm', 'Arm64EncodingTableSimd.cpp')
OUTPUT = os.path.join(armlib.REPO, 'Source', 'dismount', 'proc', 'arm', 'Arm64SemanticTableSimd.cpp')

# The mnemonics which are NOT lifted, and why (regular expressions, full match)
UNLIFTED = [
]

# (regular expression, category, units, properties). First match wins. The names are
# CATEGORY_x, UNIT_x, PROPERTY_x of OpcodeClassification
RULES = [
    # cryptography
    (r'aes[a-z]*|sha[0-9a-z]*|sm3[a-z0-9]*|sm4[a-z]*|pmull2?|rax1|eor3|bcax|xar',
     'CRYPTO', ['CRYPTO'], []),
    # structure loads and stores
    (r'ld[1-4]r?|ldap1', 'LOAD', ['LOAD', 'VECTOR_PERMUTE'], ['READS_MEMORY']),
    (r'st[1-4]|stl1', 'STORE', ['STORE', 'VECTOR_PERMUTE'], ['WRITES_MEMORY']),
    # scalar and vector floating point moves
    (r'fmov', 'MOVE', ['FLOAT_ADD'], []),
    (r'fcmp|fcmpe|fccmp|fccmpe', 'COMPARE', ['FLOAT_ADD'], []),
    (r'fcsel', 'CONDITIONAL_MOVE', ['FLOAT_ADD'], []),
    (r'fjcvtzs|fcvt[a-z0-9]*|scvtf|ucvtf|bfcvt[a-z0-9]*|bf[12]cvtl2?|f[12]cvtl2?',
     'CONVERT', ['FLOAT_CONVERT'], []),
    (r'fdiv|fsqrt|frecpe|frsqrte|frecpx|frecps|frsqrts', 'VECTOR_FLOAT', ['FLOAT_DIVIDE', 'VECTOR_FLOAT'], []),
    (r'fmul|fmulx|fnmul|fmadd|fmsub|fnmadd|fnmsub|fmla|fmls|fmla[a-z]*|fmls[a-z]*|fmlal[a-z0-9]*|fmlsl[0-9]*|'
     r'fcmla|fdot|fmmla|bfdot|bfmmla|bfmlal[bt]|fscale',
     'VECTOR_FLOAT', ['FLOAT_MULTIPLY', 'VECTOR_FLOAT'], []),
    (r'f[a-z0-9]*', 'VECTOR_FLOAT', ['FLOAT_ADD', 'VECTOR_FLOAT'], []),
    # integer vector permutes and moves
    (r'zip[12]|uzp[12]|trn[12]|ext|rev16|rev32|rev64|tbl|tbx|dup|ins|mov|umov|smov|xtn2?|sxtl2?|uxtl2?|'
     r'fcvtn2?',
     'VECTOR_PERMUTE', ['VECTOR_PERMUTE'], []),
    (r'and|orr|eor|bic|orn|not|mvn|bsl|bit|bif|movi|mvni', 'LOGIC', ['VECTOR_INTEGER'], []),
    (r'cmeq|cmge|cmgt|cmhi|cmhs|cmle|cmlt|cmtst', 'COMPARE', ['VECTOR_INTEGER'], []),
    (r'(s|u)?shl|(s|u)?shr|(s|u)?sra|(s|u)?rshr|(s|u)?rsra|sri|sli|(s|u)?shll2?|(s|u)?rshl|'
     r'(sq|uq)(r)?shl|sqshlu|(sq|uq)(r)?shr[a-z]*2?|(sq|uq)?rshrn2?|shrn2?',
     'SHIFT', ['VECTOR_INTEGER', 'SHIFTER'], []),
    (r'(s|u)?mul[a-z0-9]*|mul|mla|mls|pmul|(sq)?r?dmul[a-z0-9]*|(sq)r?dml[as]l2?|sqrdml[as]h|(s|u)(mlal|mlsl)2?|'
     r'(s|u)?dot|sudot|usdot|(s|u)?mmla|usmmla',
     'MULTIPLY', ['VECTOR_INTEGER', 'INTEGER_MULTIPLY'], []),
    (r'.*', 'VECTOR_INTEGER', ['VECTOR_INTEGER'], []),
]

NZCV = ('SemanticFlags::FLAG_SIGN | SemanticFlags::FLAG_ZERO | SemanticFlags::FLAG_CARRY | '
        'SemanticFlags::FLAG_OVERFLOW')
FLAGS_WRITTEN = r'fcmp|fcmpe|fccmp|fccmpe|fjcvtzs'
FLAGS_READ = r'fccmp|fccmpe|fcsel'


def simd_mnemonics():
    text = open(TABLE).read()
    names = []
    for m in re.finditer(r'\bE\("([^"]+)"', text):
        if m.group(1) not in names:
            names.append(m.group(1))
    return names


def is_lifted(name):
    for pattern, _ in UNLIFTED:
        if re.fullmatch(pattern, name):
            return False
    return True


def classify(name):
    for pattern, category, units, props in RULES:
        if re.fullmatch(pattern, name):
            return category, units, props
    return None


def flags_of(name):
    read = NZCV if re.fullmatch(FLAGS_READ, name) else '0'
    written = NZCV if re.fullmatch(FLAGS_WRITTEN, name) else '0'
    return read, written


def generate():
    out = []
    w = out.append
    w('''/*
 * Arm64SemanticTableSimd.cpp
 *
 * Implementation file
 *
 * The semantic table of the A64 scalar floating point, Advanced SIMD and cryptographic
 * instructions (see ArmSemantics.h): the mnemonics of gArm64SimdEncodingTable which the
 * lifter lifts, with their classification. Every entry is lifted by liftArm64Simd()
 * (Arm64SemanticLiftSimd.cpp), which dispatches on the mnemonic and decodes the operands.
 *
 * GENERATED by tests/arm/tools/gen_a64_simd_semantic_table.py: edit the generator, not this
 * file. The mnemonics which are not here are not lifted (OP_UNDEFINED).
 *
 * Author: Elad Raz <e@eladraz.com>
 */
#include "xStl/types.h"
#include "dismount/semantics/SemanticTemplate.h"
#include "dismount/semantics/ArchitectureDescription.h"
#include "dismount/semantics/OpcodeClassification.h"
#include "dismount/proc/arm/ArmSemantics.h"
#include "dismount/proc/arm/Arm64SemanticSimd.h"

namespace armdis {

namespace {

// An entry: the mnemonic, the category, the units, the properties, the flags
// read and written
#define A64(name, category, units, properties, read, written) \\
    { ArmSemanticEntry::ANY_OPERANDS_COUNT, \\
      { name, NULL, 0, OpcodeClassification::CATEGORY_##category, units, properties, \\
        read, written, 0, 0 }, \\
      liftArm64Simd, 0, 0, 0, 0 }
#define U_(x) OpcodeClassification::UNIT_##x
#define P_(x) OpcodeClassification::PROPERTY_##x

} // namespace

const ArmSemanticEntry gArm64SimdSemanticTable[] =
{''')
    skipped = []
    for name in simd_mnemonics():
        if not is_lifted(name):
            skipped.append(name)
            continue
        c = classify(name)
        if c is None:
            skipped.append(name)
            continue
        category, units, props = c
        read, written = flags_of(name)
        units_text = ' | '.join('U_(%s)' % u for u in units) if units else '0'
        props_text = ' | '.join('P_(%s)' % p for p in props) if props else '0'
        w('    A64("%s", %s, %s, %s, %s, %s),' % (name, category, units_text, props_text, read, written))
    w('    { 0, { NULL, NULL, 0, 0, 0, 0, 0, 0, 0, 0 }, NULL, 0, 0, 0, 0 }')
    w('};')
    w('')
    w('} // namespace armdis')
    return '\n'.join(out) + '\n', skipped


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--list-skipped', action='store_true')
    args = parser.parse_args()
    text, skipped = generate()
    if args.list_skipped:
        print(' '.join(skipped))
        return 0
    if args.check:
        return 0 if open(OUTPUT).read() == text else 1
    open(OUTPUT, 'w').write(text)
    print('wrote %s (%d not lifted)' % (OUTPUT, len(skipped)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
