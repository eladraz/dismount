#!/usr/bin/env python3
"""Write the SVE corpora of the A64 semantics tests (tests/arm/semantics/corpus/a64_sve*.s): a few
lines of every shape of every mnemonic of the SVE encoding corpus (tests/arm/corpus/a64/sve*.s),
tagged `@mode: sve` and `@feature: <llvm feature>`.

The corpus holds the lines both oracles can run, and the others tagged `@oracle: <list>`
(`unicorn`, `host`, `none`): see probe_sve_oracles.py, which sets the tag from what the oracles do
(Unicorn is QEMU 5.0 with SVE only; the Apple M4 runs the SVE and SVE2 instructions which are legal
in the streaming mode, at the vector length 512). The files:

  a64_sve1.s     FEAT_SVE (and the F32MM / F64MM matrix multiplies)
  a64_sve2.s     FEAT_SVE2
  a64_sve2p1.s   FEAT_SVE2p1 and the SME2 instructions in the SVE encoding space
  a64_sve_ext.s  SVE2 crypto and bit permute, bf16, i8mm, FP8, LUT, B16B16, SVE2p2, SVE2p3...

    gen_sve_semantics_corpus.py [--per-shape N]
"""
import argparse
import collections
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import armlib

CORPUS = os.path.join(armlib.REPO, 'tests', 'arm', 'corpus', 'a64')
OUTPUT = os.path.join(armlib.REPO, 'tests', 'arm', 'semantics', 'corpus')

FILES = [
    ('a64_sve1.s', ('sve', 'f32mm', 'f64mm', '')),
    ('a64_sve2.s', ('sve2',)),
    ('a64_sve2p1.s', ('sve2p1', 'sme', 'sme2', 'sme2p1')),
]
EXT = 'a64_sve_ext.s'

# The first fault and non fault loads are also run near the end of the memory window (the last
# bytes), where the elements fault
WINDOW_END = 0x0000010100010000


def shape(text):
    """The text with the numbers and register numbers masked: lines differ by form, not by value."""
    t = re.sub(r'0x[0-9a-f]+|-?\d+', 'N', text)
    return re.sub(r'\b([xwvqdshbzp]|pn)N\b', r'\1N', t)


def read_lines():
    rows = []
    for path in sorted(glob.glob(os.path.join(CORPUS, 'sve*.s'))):
        for raw in open(path):
            if raw.startswith('//') or not raw.strip():
                continue
            m = re.search(r'\s*// @feature: (.*)$', raw)
            feature = m.group(1).strip() if m else ''
            text = re.sub(r'\s*// @feature:.*$', '', raw.rstrip('\n')).strip()
            # x18 is the platform register and x28 the pointer of the host runner (run_semantics.py)
            if re.search(r'\b[xw](18|28)\b', text):
                continue
            rows.append((text, feature))
    return rows


# movprfx with the instruction it prefixes (the constructive form of a destructive instruction)
PREFIXED = [
    'movprfx z0, z1 ; add z0.s, p0/m, z0.s, z2.s',
    'movprfx z3.b, p1/m, z4.b ; sub z3.b, p1/m, z3.b, z5.b',
    'movprfx z6.d, p2/z, z7.d ; mul z6.d, p2/m, z6.d, z8.d',
    'movprfx z9.s, p3/z, z10.s ; fadd z9.s, p3/m, z9.s, z11.s',
    'movprfx z12, z13 ; asr z12.h, p4/m, z12.h, #3',
    'movprfx z14, z15 ; mla z14.s, p5/m, z16.s, z17.s',
]


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--per-shape', type=int, default=2)
    args = parser.parse_args()

    picked = collections.OrderedDict()
    for text, feature in read_lines():
        key = (shape(text), feature)
        bucket = picked.setdefault(key, [])
        if len(bucket) < args.per_shape and text not in [t for t, _ in bucket]:
            bucket.append((text, feature))

    outputs = collections.OrderedDict((name, []) for name, _ in FILES)
    outputs[EXT] = []
    for key, bucket in picked.items():
        for text, feature in bucket:
            # A movprfx must be followed by the instruction it prefixes: see PREFIXED
            if text.split()[0] == 'movprfx':
                continue
            name = EXT
            for filename, features in FILES:
                if feature in features:
                    name = filename
                    break
            tags = '// @mode: sve @feature: %s' % feature if feature else '// @mode: sve'
            outputs[name].append('%s %s' % (text, tags))
            mnemonic = text.split()[0]
            if re.match(r'ld(ff|nf)1', mnemonic) and 'z' not in text.split('[')[-1]:
                for end_offset in (6, 30, 130):
                    outputs[name].append('%s %s @state: x4=%x' % (text, tags, WINDOW_END - end_offset))
    outputs['a64_sve1.s'] += ['%s // @mode: sve @feature: sve' % t for t in PREFIXED]
    for name, lines in outputs.items():
        with open(os.path.join(OUTPUT, name), 'w') as f:
            f.write('// Generated by tests/arm/tools/gen_sve_semantics_corpus.py: the shapes of the SVE encoding\n'
                    '// corpus (tests/arm/corpus/a64/sve*.s). `@oracle:` is set by probe_sve_oracles.py.\n')
            f.write('\n'.join(lines) + '\n')
        print('%s: %d lines' % (name, len(lines)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
