#!/usr/bin/env python3
"""Write the comprehensive corpora of the A64 scalar floating point, Advanced SIMD and cryptographic
semantics (tests/arm/semantics/TEST_PLAN.md), from the lines of the encoding corpus
(tests/arm/corpus/a64/simd*.s): every mnemonic of gArm64SimdEncodingTable in every shape of operands
(arrangements, scalar sizes, elements, immediates), a few register / immediate variants of each.

    a64_fp_all.s       scalar and vector floating point, the conversions, FP16, FHM, BF16, FCMA, JSCVT, FRINTTS,
                       FP8, FAMINMAX, FPRCVT
    a64_neon_all.s     Advanced SIMD integer (arithmetic, logic, shifts, saturating, narrow / widen, permutes,
                       dot products, matrix multiply)
    a64_crypto_all.s   AES, SHA, SM3, SM4, PMULL
    a64_simdmem_all.s  the structure loads and stores

The lines are chosen so that every engine runs them the same way: no x18 / x28 (the host runner), no
UNPREDICTABLE register overlaps.

    gen_semantics_corpus_simd.py [--per-shape N]
"""
import argparse
import collections
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import armlib

CORPUS = os.path.join(armlib.REPO, 'tests', 'arm', 'corpus', 'a64')
OUT = os.path.join(armlib.REPO, 'tests', 'arm', 'semantics', 'corpus')

CRYPTO = re.compile(r'^(aes|sha1|sha256|sha512|sm3|sm4|pmull|rax1|eor3|bcax|xar)')
MEMORY = re.compile(r'^(ld[1-4]|st[1-4]|ldap1|stl1)')
FLOAT = re.compile(r'^(f|scvtf|ucvtf|bf|luti|famax|famin|fscale)')


def mnemonic_of(text):
    return text.split()[0].lower()


def shape_of(text):
    """The operands of the text with the register numbers and the immediates removed."""
    parts = text.split(None, 1)
    ops = parts[1] if len(parts) > 1 else ''
    ops = re.sub(r'\b([vqdshbxwz])\d+\b', r'\1#', ops)
    ops = re.sub(r'#-?(0x)?[0-9a-fA-F.]+', '#N', ops)
    ops = re.sub(r'\[\d+\]', '[i]', ops)
    ops = re.sub(r'\b(eq|ne|hs|lo|mi|pl|vs|vc|hi|ls|ge|lt|gt|le|al|nv|cs|cc)\b', 'cc', ops)
    return parts[0].lower() + ' ' + ops


def is_selected(text):
    t = text.lower()
    # the reserved registers of the host runner
    if re.search(r'\b[xw](18|28)\b', t):
        return False
    # a post index by the base register or the transfer through sp is not interesting
    m = re.match(r'^(ld[1-4]r?|st[1-4]|ldap1|stl1)\s+\{[^}]*\}(?:\[\d+\])?,\s*\[(x\d+|sp)\](?:,\s*(x\d+))?', t)
    if m and m.group(3) and m.group(3) == m.group(2):
        return False
    return True


def area_of(mnemonic):
    if CRYPTO.match(mnemonic):
        return 'crypto'
    if MEMORY.match(mnemonic):
        return 'simdmem'
    if FLOAT.match(mnemonic):
        return 'fp'
    return 'neon'


FILES = {
    'fp': ('a64_fp_all.s', 'scalar and vector floating point, the conversions with the integers'),
    'neon': ('a64_neon_all.s', 'Advanced SIMD integer'),
    'crypto': ('a64_crypto_all.s', 'cryptography'),
    'simdmem': ('a64_simdmem_all.s', 'Advanced SIMD structure loads and stores'),
}


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--per-shape', type=int, default=3)
    args = parser.parse_args()
    groups = collections.OrderedDict()
    seen = set()
    for path in sorted(glob.glob(os.path.join(CORPUS, 'simd*.s'))):
        for raw in open(path):
            if raw.startswith('//') or not raw.strip():
                continue
            m = re.match(r'^(.*?)\s*//\s*@feature:\s*(\S+)\s*$', raw.rstrip('\n'))
            text, feature = (m.group(1), m.group(2)) if m else (raw.split('//')[0].strip(), '')
            text = text.strip()
            if not text or text in seen or not is_selected(text):
                continue
            seen.add(text)
            groups.setdefault(shape_of(text), []).append((text, feature))

    by_area = collections.defaultdict(lambda: collections.defaultdict(list))
    for shape, items in groups.items():
        mnemonic = shape.split()[0]
        count = args.per_shape
        # the immediates and the elements: more variants
        if '#N' in shape or '[i]' in shape:
            count += 3
        if len(items) > count:
            step = len(items) / float(count)
            items = [items[int(i * step)] for i in range(count)]
        by_area[area_of(mnemonic)][mnemonic].extend(items)

    total = 0
    for area, (name, description) in FILES.items():
        out = ['// Generated by tests/arm/tools/gen_semantics_corpus_simd.py: do not edit.',
               '// The A64 %s instructions which dismount lifts, run with' % description,
               '//   run_semantics.py --arch a64 --file %s [--oracle host]' % name[:-2],
               '// No x18 / x28 (the host runner).', '']
        for mnemonic in sorted(by_area[area]):
            out.append('// --- %s' % mnemonic)
            for text, feature in by_area[area][mnemonic]:
                out.append('%s%s' % (text, ('   // @feature: ' + feature) if feature else ''))
                total += 1
        with open(os.path.join(OUT, name), 'w') as f:
            f.write('\n'.join(out) + '\n')
    print('%d lines' % total)


if __name__ == '__main__':
    main()
