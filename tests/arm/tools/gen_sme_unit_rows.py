#!/usr/bin/env python3
"""Generate tests/arm/Arm64SmeTestRows.inc, the rows of tests/TestArm64Sme.cpp:
{address, word, "text", "features"} for the SME corpus (tests/arm/corpus/a64/
sme*.s: a few shapes of every mnemonic), and the words of the SME class which
objdump says are not instructions. The features of a row are the LLVM names
separated by commas ("sme2,sme-i16i64"). The texts are what objdump prints for the
words, so the unit test pins the LLVM syntax.

    gen_sme_unit_rows.py [--per-mnemonic N]
"""
import argparse
import collections
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import armlib

OUTPUT = os.path.join(armlib.REPO, 'tests', 'arm', 'Arm64SmeTestRows.inc')
CORPUS = os.path.join(armlib.REPO, 'tests', 'arm', 'corpus', 'a64')


def shape(text):
    """The text with the numbers and the register numbers removed: rows differ
    by form and not by value."""
    return re.sub(r'\b([xwvqdshbzp]|pn)\d+\b', r'\1N', re.sub(r'0x[0-9a-f]+|\d+', 'N', text))


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--per-mnemonic', type=int, default=4)
    args = parser.parse_args()

    lines = []
    features = []
    for path in sorted(glob.glob(os.path.join(CORPUS, 'sme*.s'))):
        for raw in open(path):
            if raw.startswith('//') or not raw.strip():
                continue
            m = re.search(r'\s*// @feature: (.*)$', raw)
            features.append(','.join(m.group(1).split()) if m else '')
            lines.append(re.sub(r'\s*// @feature:.*$', '', raw.rstrip('\n')).strip())
    results = armlib.clang_assemble(lines, 'a64')
    words = []
    sources = []
    for line, feature, (status, data) in zip(lines, features, results):
        if status == 'ok':
            words.append(armlib.hex_bytes_to_word(data))
            sources.append(feature)
    texts, addresses = armlib.objdump_chunks(words, 'a64')
    picked = collections.defaultdict(list)
    for word, address, text, feature in zip(words, addresses, texts, sources):
        if text == '<unknown>':
            continue
        mnemonic = text.split(' ')[0]
        shapes = [shape(t) for _, _, t, _ in picked[mnemonic]]
        if len(picked[mnemonic]) < args.per_mnemonic and shape(text) not in shapes:
            picked[mnemonic].append((address, word, text, feature))
    rows = []
    for mnemonic in sorted(picked):
        rows.extend(picked[mnemonic])

    rng = armlib.seeded_rng(11)
    invalid = []
    while len(invalid) < 120:
        w = rng.getrandbits(32)
        if armlib.a64_class(w) == 'sme' and (w >> 24) not in (0xa0, 0xa1):
            invalid.append(w)
    inv_texts = armlib.objdump_words(invalid)
    invalid = [w for w, t in zip(invalid, inv_texts) if t == '<unknown>']
    # The reserved combinations next to the encodings: one bit flipped
    near = []
    for text_row in rows[::7]:
        w = text_row[1] ^ (1 << rng.randrange(32))
        if armlib.a64_class(w) == 'sme':
            near.append(w)
    near_texts = armlib.objdump_words(near)
    invalid += [w for w, t in zip(near, near_texts) if t == '<unknown>']

    with open(OUTPUT, 'w') as f:
        f.write('// Generated by tests/arm/tools/gen_sme_unit_rows.py: the rows of\n')
        f.write('// tests/TestArm64Sme.cpp. {address, word, text, feature}: LLVM text.\n')
        f.write('#define ARM64_SME_TEXT_ROWS \\\n')
        for address, word, text, feature in rows:
            f.write('    { 0x%x, 0x%08x, "%s", "%s" }, \\\n' % (address, word, text.replace('"', '\\"'), feature))
        f.write('\n#define ARM64_SME_INVALID_WORDS \\\n')
        for w in invalid:
            f.write('    0x%08x, \\\n' % w)
        f.write('\n')
    print('%d rows, %d invalid words' % (len(rows), len(invalid)))


if __name__ == '__main__':
    main()
