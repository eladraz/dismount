#!/usr/bin/env python3
"""Generate the SME corpus of the semantics tests (tests/arm/semantics/corpus/a64_sme.s and
a64_sme_modes.s) from the encoding table (Source/dismount/proc/arm/Arm64EncodingTableSme.cpp): for
every entry whose feature the M4 runs (FEAT_SME, FEAT_SME2, FEAT_SME_F64F64, FEAT_SME_I16I64) some
words of the entry with random operand fields are disassembled with dismount_cli, and the text is
kept when clang assembles it back to the same word (so the corpus is the syntax of LLVM and the
fields are legal). Lines of the file a64_sme.s run in the streaming mode with za enabled; the file
a64_sme_modes.s has, for every entry, a line in the mode where the instruction is undefined (not
streaming: `nosm`, za disabled: `noza`) or runs (`nosm` for ldr / str / zero).

    gen_sme_semantics_corpus.py [--per-entry N] [--seed N]

Author: Elad Raz <e@eladraz.com>
"""
import argparse
import os
import random
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'tests', 'arm', 'semantics'))
import armasm  # noqa: E402

TABLE = os.path.join(REPO, 'Source', 'dismount', 'proc', 'arm', 'Arm64EncodingTableSme.cpp')
CLI = os.path.join(REPO, 'out', 'bin', 'dismount_cli')
CORPUS = os.path.join(REPO, 'tests', 'arm', 'semantics', 'corpus')
M4_FEATURES = {'FEAT_SME': 'sme', 'FEAT_SME2': 'sme2', 'FEAT_SME_F64F64': 'sme-f64f64',
               'FEAT_SME_I16I64': 'sme-i16i64'}


def entries():
    text = open(TABLE).read()
    out = []
    for m in re.finditer(r'\n    E\("([a-z0-9_]+)", (0x[0-9a-f]+), (0x[0-9a-f]+), (FEAT_\w+), ([A-Z_| 0-9]+), ', text):
        out.append((m.group(1), int(m.group(2), 16), int(m.group(3), 16), m.group(4), m.group(5)))
    return out


def disassemble(words):
    inp = ''.join('%08x\n' % w for w in words)
    res = subprocess.run([CLI, 'dis', '--arch', 'a64'], input=inp, capture_output=True, text=True).stdout.splitlines()
    out = []
    for line in res:
        out.append(line[5:].strip() if line.startswith('OK ') else None)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--per-entry', type=int, default=2)
    ap.add_argument('--seed', type=int, default=7)
    args = ap.parse_args()
    rng = random.Random(args.seed)
    ents = entries()
    cand = []
    for i, (mn, mask, value, feat, flags) in enumerate(ents):
        if feat not in M4_FEATURES:
            continue
        for _ in range(12):
            cand.append((i, value | (rng.getrandbits(32) & ~mask & 0xFFFFFFFF)))
    texts = disassemble([w for _, w in cand])
    # the text must assemble to the same word
    ok = [(i, w, t) for (i, w), t in zip(cand, texts) if t and not t.startswith('INVALID')]
    asm = armasm.assemble('a64', [t.split(' ', 1)[1] if t[0].isdigit() else t for _, _, t in ok])
    per = {}
    for (i, w, t), (hexb, err) in zip(ok, asm):
        if err:
            continue
        t = t.split(' ', 1)[1] if t[0].isdigit() else t
        if int.from_bytes(bytes.fromhex(hexb), 'little') != w:
            continue
        # x18 is the platform register and x28 the pointer of the runner of the host oracle
        if re.search(r'\b[xw](18|28)\b', t):
            continue
        lst = per.setdefault(i, [])
        if len(lst) < args.per_entry and t not in [x for x in lst]:
            lst.append(t)
    main_lines = []
    mode_lines = []
    missing = []
    for i, (mn, mask, value, feat, flags) in enumerate(ents):
        if feat not in M4_FEATURES:
            continue
        if i not in per:
            missing.append((i, mn))
            continue
        streaming = 'STREAMING_ONLY' in flags
        for t in per[i]:
            main_lines.append('%-60s // @feature: %s @mode: za' % (t, M4_FEATURES[feat]))
        t = per[i][0]
        uses_za = ('za' in t) or ('zt0' in t)
        mode_lines.append('%-60s // @feature: %s @mode: nosm' % (t, M4_FEATURES[feat]))
        if uses_za:
            # sm=1, za=0: undefined (every ZA access traps); the zeroing of za and ldr / str need za too
            mode_lines.append('%-60s // @feature: %s @mode: noza' % (t, M4_FEATURES[feat]))
    head = ('// SME and SME2 in the streaming mode with ZA enabled (SVL 512): only the host runs these (Unicorn has\n'
            '// no SME and reports ORACLE_ERR). GENERATED by tests/arm/tools/gen_sme_semantics_corpus.py from the\n'
            '// encoding table (%d lines: %d entries); edit the generator.\n' % (len(main_lines), len(per)))
    with open(os.path.join(CORPUS, 'a64_sme.s'), 'w') as f:
        f.write(head)
        f.write('\n'.join(main_lines) + '\n')
    head = ('// SME instructions outside of their mode, one line per entry: `nosm` is ZA enabled without the\n'
            '// streaming mode (every streaming instruction is undefined, ldr / str / zero of za run), `noza` is the\n'
            '// streaming mode without ZA (every ZA access is undefined). GENERATED by\n'
            '// tests/arm/tools/gen_sme_semantics_corpus.py.\n')
    with open(os.path.join(CORPUS, 'a64_sme_modes.s'), 'w') as f:
        f.write(head)
        f.write('\n'.join(mode_lines) + '\n')
    print('%d lines in a64_sme.s, %d in a64_sme_modes.s; entries without a legal sample: %s' % (
        len(main_lines), len(mode_lines), ', '.join('%d:%s' % x for x in missing)))


if __name__ == '__main__':
    main()
