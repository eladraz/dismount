M32 = (1 << 32) - 1
M64 = (1 << 64) - 1
M128 = (1 << 128) - 1


def tokens(d):
    parts = []
    for key, value in d.items():
        if key == 'mem':
            parts.append('mem=' + ','.join('%x:%s' % (a, bytes(b).hex()) for a, b in value))
        else:
            parts.append('%s=%x' % (key, value))
    return ' '.join(parts)


class Rows(object):
    def __init__(self):
        self.rows = []

    def add(self, text, setup, expect):
        self.rows.append((text, setup, expect))

    def write(self, output, macro, generator):
        pieces = []
        for text, _, _ in self.rows:
            pieces += text.split(' ; ')
        unique = sorted(set(pieces))
        assembled = dict(zip(unique, armasm.assemble('a64', unique)))
        out = ['// Generated by tests/arm/tools/%s: the rows of tests/TestArm64SemanticsSimd.cpp.' % generator,
               '// { {words}, count, "text", "setup", "expected" }',
               '#define %s \\' % macro]
        for text, setup, expect in self.rows:
            words = []
            for piece in text.split(' ; '):
                hexb, err = assembled[piece]
                if err:
                    raise SystemExit('%s: %s' % (piece, err))
                words.append(int.from_bytes(bytes.fromhex(hexb), 'little'))
            out.append('    { {%s}, %d, "%s", "%s", "%s" }, \\' % (
                ', '.join('0x%08x' % w for w in words), len(words), text, tokens(setup), tokens(expect)))
        out.append('')
        with open(output, 'w') as f:
            f.write('\n'.join(out) + '\n')
        print('wrote %s: %d rows' % (output, len(self.rows)))


def mask(bits):
    return (1 << bits) - 1


def lane(value, index, bits):
    return (value >> (index * bits)) & mask(bits)


def set_lane(value, index, bits, lane_value):
    value &= ~(mask(bits) << (index * bits))
    return value | ((lane_value & mask(bits)) << (index * bits))


def le(value, size):
    return list((value & mask(size * 8)).to_bytes(size, 'little'))
