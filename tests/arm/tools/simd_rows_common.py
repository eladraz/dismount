"""Shared by the generators of the A64 SIMD unit rows (gen_simd_semantic_rows_*.py): the row syntax of
tests/TestArm64SemanticsSimd.cpp (the same as tests/arm/Arm64SemanticRows.inc), the assembly of the words
with clang and the writer of the .inc file.

A row is (text, setup, expected): the instruction text (`;` joins a sequence), and two dictionaries of
the tokens x0..x30, sp, nzcv, fpcr, fpsr, v0..v31 (ints), mem (a list of (address, bytes)).
"""
