#!/usr/bin/env python3
"""Generate tests/arm/Arm64TestRows.inc, the rows of tests/TestArm64Disassembler.cpp:
{address, word, "text"} for every mnemonic of the base table (a few shapes of
each), and the words which have to be invalid. The texts are what objdump
prints for the words, so the unit test pins the LLVM syntax.

    gen_unit_rows.py [--per-mnemonic N]
"""
import argparse
import collections
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import armlib

OUTPUT = os.path.join(armlib.REPO, 'tests', 'arm', 'Arm64TestRows.inc')
CORPUS = os.path.join(armlib.REPO, 'tests', 'arm', 'corpus', 'a64')


def shape(text):
    """The shape of a text: the operands with the numbers and the register
    numbers removed, so rows differ by form and not by value."""
    return re.sub(r'\b([xwvqdshbzp])\d+\b', r'\1N', re.sub(r'0x[0-9a-f]+|\d+', 'N', text))


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--per-mnemonic', type=int, default=3)
    args = parser.parse_args()

    lines = []
    for path in sorted(glob.glob(os.path.join(CORPUS, '*.s'))):
        name = os.path.basename(path)[:-2]
        # The scalar floating point and Advanced SIMD lines are the rows of
        # tests/TestArm64Simd.cpp (gen_simd_unit_rows.py)
        if name in ('simd', 'sve', 'sme') or name.startswith('simd-'):
            continue
        for raw in open(path):
            if raw.startswith('//') or not raw.strip():
                continue
            lines.append(re.sub(r'\s*// @feature:.*$', '', raw.rstrip('\n')).strip())
    results = armlib.clang_assemble(lines, 'a64')
    words = []
    sources = []
    for line, (status, data) in zip(lines, results):
        if status == 'ok':
            words.append(armlib.hex_bytes_to_word(data))
            sources.append(line)
    texts, addresses = armlib.objdump_chunks(words, 'a64')
    picked = collections.defaultdict(list)
    for word, address, text in zip(words, addresses, texts):
        if text == '<unknown>':
            continue
        mnemonic = text.split(' ')[0]
        shapes = [shape(t) for _, _, t in picked[mnemonic]]
        if len(picked[mnemonic]) < args.per_mnemonic and shape(text) not in shapes:
            picked[mnemonic].append((address, word, text))
    # Rows at the addresses of the listing, the pc relative text depends on it
    rows = []
    for mnemonic in sorted(picked):
        rows.extend(picked[mnemonic])
    rng = armlib.seeded_rng(5)
    invalid = []
    while len(invalid) < 60:
        w = rng.getrandbits(32)
        if armlib.a64_class(w) == 'base':
            invalid.append(w)
    inv_texts = armlib.objdump_words(invalid)
    invalid = [w for w, t in zip(invalid, inv_texts) if t == '<unknown>']

    with open(OUTPUT, 'w') as f:
        f.write('// Generated by tests/arm/tools/gen_unit_rows.py: the rows of\n')
        f.write('// tests/TestArm64Disassembler.cpp. {address, word, text}: LLVM text.\n')
        f.write('#define ARM64_TEXT_ROWS \\\n')
        for address, word, text in rows:
            f.write('    { 0x%x, 0x%08x, "%s" }, \\\n' % (address, word, text.replace('"', '\\"')))
        f.write('\n#define ARM64_INVALID_WORDS \\\n')
        for w in invalid:
            f.write('    0x%08x, \\\n' % w)
        f.write('\n')
    print('%d rows, %d invalid words' % (len(rows), len(invalid)))


if __name__ == '__main__':
    main()
