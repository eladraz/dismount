#!/usr/bin/env python3
"""Write tests/arm/semantics/corpus/a64_neon_edge.s: the lines of a64_neon_all.s (up to a few per mnemonic and
shape of operands) with directed states (`// @state:`) whose vector lanes are the edge values of the integer
instructions: the minimum and maximum of the signed and unsigned ranges, +-1, 0, the shift counts (the low byte
of a lane is a signed count for sshl and friends: 0, 1, e-1, e, e+1, -1, -e, -e-1, 0x7f, 0x80) and the alternating
bit patterns. They reach the saturation (FPSR.QC), the rounding and the overflow paths which random lanes rarely do.

    gen_semantics_neon_edges.py [--states N]
"""
import argparse
import collections
import os
import random
import re
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import armlib

CORPUS = os.path.join(armlib.REPO, 'tests', 'arm', 'semantics', 'corpus')
SOURCE = os.path.join(CORPUS, 'a64_neon_all.s')
OUTPUT = os.path.join(CORPUS, 'a64_neon_edge.s')


def shape_of(text):
    parts = text.split(None, 1)
    ops = parts[1] if len(parts) > 1 else ''
    ops = re.sub(r'\b([vqdshbxwz])\d+\b', r'\1#', ops)
    ops = re.sub(r'#-?(0x)?[0-9a-fA-F.]+', '#N', ops)
    ops = re.sub(r'\[\d+\]', '[i]', ops)
    return parts[0].lower() + ' ' + ops


def element_sizes(text):
    """The element sizes in bits of the registers of the text."""
    sizes = set()
    for m in re.finditer(r'\b[vqdshb]\d+(?:\.(\d*)([bhsd]))?', text):
        letter = m.group(2) if m.group(2) else None
        if letter is None:
            letter = re.match(r'[vqdshb]', m.group(0)).group(0)
        bits = {'b': 8, 'h': 16, 's': 32, 'd': 64, 'q': 128}.get(letter)
        if bits and bits <= 64:
            sizes.add(bits)
    return sorted(sizes) or [32]


def edge_values(e):
    m = (1 << e) - 1
    smax = (1 << (e - 1)) - 1
    values = [0, 1, 2, e - 1, e, e + 1, m, m - 1, (-e) & m, (-e - 1) & m, smax, smax + 1, smax + 2,
              smax - 1, 0x7f & m, 0x80 & m, 0xff & m, int('55' * (e // 8), 16), int('aa' * (e // 8), 16), 3 & m]
    return [v & m for v in values]


def make_vector(rng, e):
    values = edge_values(e)
    v = 0
    for i in range(128 // e):
        v |= rng.choice(values) << (i * e)
    return v


EXTRA = ['cmlo v0.4s, v1.4s, v2.4s', 'cmlo v0.8b, v1.8b, v2.8b', 'cmls v0.16b, v1.16b, v2.16b', 'cmls d0, d1, d2',
         'cmlo d0, d1, d2', 'sxtl v0.8h, v1.8b', 'sxtl2 v0.4s, v1.8h', 'uxtl v0.2d, v1.2s', 'uxtl2 v0.8h, v1.16b',
         'ins v0.s[1], w1', 'ins v0.b[15], w2', 'ins v0.d[1], x3', 'ins v0.h[2], v1.h[5]', 'not v0.16b, v1.16b',
         'mvn v0.8b, v1.8b', 'mov v0.16b, v1.16b', 'mov v3.d[1], v4.d[0]', 'mov b0, v1.b[7]', 'mov w0, v1.s[3]',
         'mov x0, v1.d[1]', 'mov v0.s[2], w5']


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--states', type=int, default=14)
    parser.add_argument('--per-shape', type=int, default=3)
    args = parser.parse_args()
    groups = collections.OrderedDict()
    for raw in open(SOURCE):
        if raw.startswith('//') or not raw.strip():
            continue
        text = raw.split('//')[0].strip()
        groups.setdefault(shape_of(text), []).append(text)
    out = ['// Generated by tests/arm/tools/gen_semantics_neon_edges.py: do not edit.',
           '// The lines of a64_neon_all.s with directed states of edge values (saturation, shift counts).', '']
    total = 0
    for shape, lines in groups.items():
        for text in lines[:args.per_shape]:
            regs = sorted(set(int(m.group(1)) for m in re.finditer(r'\b[vqdshb](\d+)\b', text)))
            sizes = element_sizes(text)
            rng = random.Random(zlib.crc32(text.encode()))
            states = []
            for _ in range(args.states):
                tokens = []
                for r in regs:
                    e = rng.choice(sizes)
                    tokens.append('v%d=%032x' % (r, make_vector(rng, e)))
                states.append('@state: ' + ' '.join(tokens))
            out.append('%s   // %s' % (text, '  '.join(states)))
            total += 1
    # the aliases which have an entry of their own in the encoding table
    out.append('// --- the alias entries')
    for text in EXTRA:
        out.append(text)
        total += 1
    open(OUTPUT, 'w').write('\n'.join(out) + '\n')
    print('%d lines' % total)


if __name__ == '__main__':
    main()
