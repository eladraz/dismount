#!/usr/bin/env python3
"""Generate tests/arm/Arm64SimdTestRows.inc, the rows of tests/TestArm64Simd.cpp:
{address, word, "text", "features"} for every form of every mnemonic of the
scalar floating point, Advanced SIMD and cryptographic corpus
(tests/arm/corpus/a64/simd*.s), and the words which have to be invalid. The
texts are what objdump prints for the words, so the unit test pins the LLVM
syntax; "features" is the LLVM feature list which the instruction needs ("" for
ARMv8.0).

    gen_simd_unit_rows.py [--per-shape N]
"""
import argparse
import collections
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import armlib
import fuzz_decode

OUTPUT = os.path.join(armlib.REPO, 'tests', 'arm', 'Arm64SimdTestRows.inc')
CORPUS = os.path.join(armlib.REPO, 'tests', 'arm', 'corpus', 'a64')


def shape(text):
    """The shape of a text: the operands with the numbers and the register
    numbers removed, so rows differ by form and not by value."""
    text = re.sub(r'\b([xwvqdshbzp])\d+\b', r'\1N', text)
    text = re.sub(r'#-?(0x[0-9a-f]+|\d+(\.\d+)?)', '#N', text)
    return re.sub(r'\[\d+\]', '[N]', text)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--per-shape', type=int, default=1)
    args = parser.parse_args()

    lines = []
    features = []
    for path in sorted(glob.glob(os.path.join(CORPUS, 'simd*.s'))):
        for raw in open(path):
            if raw.startswith('//') or not raw.strip():
                continue
            m = re.search(r'\s*// @feature: (.*)$', raw)
            required = m.group(1).split() if m else []
            lines.append(re.sub(r'\s*// @feature:.*$', '', raw.rstrip('\n')).strip())
            features.append(required)
    results = armlib.clang_assemble(lines, 'a64')
    words = []
    required_of = []
    for line, required, (status, data) in zip(lines, features, results):
        if status == 'ok':
            words.append(armlib.hex_bytes_to_word(data))
            required_of.append(required)
    texts, addresses = armlib.objdump_chunks(words, 'a64')

    picked = collections.defaultdict(list)
    rows = []
    for word, address, text, required in zip(words, addresses, texts, required_of):
        if text == '<unknown>':
            continue
        key = shape(text)
        if len(picked[key]) < args.per_shape:
            picked[key].append(word)
            rows.append((text.split(' ')[0], key, address, word, text, required))
    rows.sort(key=lambda r: (r[0], r[1], r[3]))

    # The invalid words: the neighbours of the encodings (a flipped fixed bit)
    # which objdump rejects, from the simd class
    rng = armlib.seeded_rng(11)
    table = [r for r in armlib.entries('a64') if armlib.a64_class(r[1]) == 'simd']
    candidates = []
    while len(candidates) < 40000:
        mask, value = rng.choice(table)[:2]
        word = value | (rng.getrandbits(32) & ~mask & 0xffffffff)
        for _ in range(rng.choice((1, 1, 2))):
            word ^= 1 << rng.randrange(32)
        word &= 0xffffffff
        if armlib.a64_class(word) == 'simd':
            candidates.append(word)
    candidates = sorted(set(candidates))
    cand_texts, _ = armlib.objdump_chunks(candidates, 'a64')
    invalid = [w for w, t in zip(candidates, cand_texts) if t == '<unknown>']
    rng.shuffle(invalid)
    invalid = sorted(invalid[:400])

    with open(OUTPUT, 'w') as f:
        f.write('// Generated by tests/arm/tools/gen_simd_unit_rows.py: the rows of\n')
        f.write('// tests/TestArm64Simd.cpp. {address, word, text, features}: LLVM text.\n')
        f.write('#define ARM64_SIMD_TEXT_ROWS \\\n')
        for _, _, address, word, text, required in rows:
            f.write('    { 0x%x, 0x%08x, "%s", "%s" }, \\\n' % (
                address, word, text.replace('"', '\\"'), ','.join(required)))
        f.write('\n#define ARM64_SIMD_INVALID_WORDS \\\n')
        for w in invalid:
            f.write('    0x%08x, \\\n' % w)
        f.write('\n')
    print('%d rows, %d invalid words' % (len(rows), len(invalid)))


if __name__ == '__main__':
    main()
