def gen_t32_it():
    c = Corpus('t32_it.s', 'T32 IT blocks: every pattern, every condition, taken and not taken instructions')
    bodies = [
        ('add{c} r0, r1, r2', 'sub{ic} r0, r1, #1'),
        ('mov{c} r0, #5', 'mov{ic} r0, #7'),
        ('ldr{c} r0, [r4]', 'str{ic} r1, [r4, #8]'),
        ('adc{c} r0, r1, r2', 'sbc{ic} r0, r1, r2'),
        ('lsl{c} r0, r1, #3', 'lsr{ic} r0, r1, #3'),
        ('mul{c} r0, r1, r0', 'and{ic} r2, r3'),
        ('cmp{c} r0, r1', 'add{ic} r2, r2, #1'),
        ('ldrb{c} r0, [r4, #1]', 'ldrh{ic} r1, [r4, #2]'),
    ]
    inv = {'eq': 'ne', 'ne': 'eq', 'cs': 'cc', 'cc': 'cs', 'mi': 'pl', 'pl': 'mi', 'vs': 'vc', 'vc': 'vs',
           'hi': 'ls', 'ls': 'hi', 'ge': 'lt', 'lt': 'ge', 'gt': 'le', 'le': 'gt'}
    patterns = ['', 't', 'e', 'tt', 'te', 'et', 'ee', 'ttt', 'tte', 'tet', 'tee', 'ett', 'ete', 'eet', 'eee']
    def pattern_mnemonic(p):
        return 'it' + p
    count = 0
    for cond in CONDS:
        for p in patterns:
            slots = ['t'] + list(p)
            insts = []
            for n, slot in enumerate(slots):
                a, b = bodies[(count + n) % len(bodies)]
                use = cond if slot == 't' else inv[cond]
                text = (a if n % 2 == 0 else b).replace('{c}', use).replace('{ic}', use)
                insts.append(text)
            c.add('%s %s ; %s' % (pattern_mnemonic(p), cond, ' ; '.join(insts)))
            count += 1
    c.comment('branches and returns at the end of a block')
    for cond in CONDS:
        c.add('it %s ; b%s #8' % (cond, cond))
        c.add('it %s ; bx%s lr' % (cond, cond), 'lr=30001', 'lr=30000')
        c.add('it %s ; blx%s r5' % (cond, cond), 'r5=20001', 'r5=20000')
        c.add('it %s ; bl%s #16' % (cond, cond))
        c.add('ite %s ; mov%s r0, #1 ; mov%s r0, #2' % (cond, cond, inv[cond]))
        c.add('itt %s ; mov%s r1, #3 ; ldr%s pc, [r4]' % (cond, cond, cond), 'mem=20004000:01000000')
        c.add('it %s ; pop%s {r0, pc}' % (cond, cond), 'mem=20008000:01000000')
        c.add('itt %s ; add%s r0, r1, r2 ; svc%s #4' % (cond, cond, cond))
    c.comment('the flags of the 16 bit instructions: not set inside of the block')
    for cond in CONDS:
        c.add('ittt %s ; add%s r0, r1, r2 ; sub%s r3, r3, #1 ; lsl%s r2, r2, #3' % (cond, cond, cond, cond))
        c.add('itee %s ; mov%s r0, #0 ; orr%s r0, r1 ; eor%s r2, r2' % (cond, cond, inv[cond], inv[cond]))
    c.write()


