SAT = ['r1=7fffffff r2=7fffffff', 'r1=80000000 r2=80000000', 'r1=7fffffff r2=1', 'r1=80000000 r2=ffffffff',
       'r1=0 r2=0', 'r1=ffffffff r2=1', 'r1=40000000 r2=40000000', 'r1=c0000000 r2=c0000000 apsr=08000000']
PAR = ['r1=7fff8000 r2=00018000', 'r1=80008000 r2=80008000', 'r1=ffff0001 r2=00010001',
       'r1=ff80007f r2=017f0080', 'r1=80ff7f01 r2=ff0180ff', 'r1=00000000 r2=00000000',
       'r1=ffffffff r2=ffffffff', 'r1=12345678 r2=9abcdef0', 'r1=7f7f7f7f r2=01010101',
       'r1=80808080 r2=80808080', 'r1=00ff00ff r2=ff00ff00', 'r1=00010002 r2=00020001']


def gen_dsp(arch):
    c = Corpus('%s_dsp.s' % arch, '%s saturating, parallel, extend, pack, bit field and reverse instructions' % arch.upper())
    thumb = arch == 't32'
    c.comment('saturating add and subtract (Q)')
    for op in ('qadd', 'qsub', 'qdadd', 'qdsub'):
        c.add('%s r0, r1, r2' % op, *SAT)
    c.comment('ssat / usat (the shift, the limits)')
    for n in (1, 2, 8, 16, 31, 32):
        c.add('ssat r0, #%d, r1' % n, 'r1=7fffffff', 'r1=80000000', 'r1=ffffff00', 'r1=100', 'r1=0')
        c.add('ssat r0, #%d, r1, lsl #4' % n, 'r1=7ffff', 'r1=fff80000')
        c.add('ssat r0, #%d, r1, asr #8' % n, 'r1=7fffffff', 'r1=80000000')
    if not thumb:
        c.add('ssat r0, #8, r1, asr #32')
    for n in (0, 1, 8, 16, 31):
        c.add('usat r0, #%d, r1' % n, 'r1=7fffffff', 'r1=80000000', 'r1=ffffff00', 'r1=100', 'r1=0', 'r1=ff')
        c.add('usat r0, #%d, r1, lsl #4' % n, 'r1=7ffff', 'r1=fff80000')
        c.add('usat r0, #%d, r1, asr #8' % n, 'r1=7fffffff', 'r1=80000000')
    for n in (1, 8, 16):
        c.add('ssat16 r0, #%d, r1' % n, 'r1=7fff8000', 'r1=00ff0100', 'r1=ff00ffff')
    for n in (0, 1, 8, 15):
        c.add('usat16 r0, #%d, r1' % n, 'r1=7fff8000', 'r1=00ff0100', 'r1=ff00ffff')
    c.comment('the parallel add and subtract (GE)')
    for prefix in ('s', 'q', 'sh', 'u', 'uq', 'uh'):
        for op in ('add16', 'add8', 'sub16', 'sub8', 'asx', 'sax'):
            c.add('%s%s r0, r1, r2' % (prefix, op), *PAR)
    c.add('sel r0, r1, r2', 'apsr=000f0000', 'apsr=00000000', 'apsr=000a0000', 'apsr=00050000', 'apsr=00030000')
    c.comment('extends')
    for op in ('sxtb', 'sxth', 'uxtb', 'uxth', 'sxtb16', 'uxtb16'):
        for rot in ('', ', ror #8', ', ror #16', ', ror #24'):
            c.add('%s r0, r1%s' % (op, rot), 'r1=80ff7f01', 'r1=01ff0180')
    for op in ('sxtab', 'sxtah', 'uxtab', 'uxtah', 'sxtab16', 'uxtab16'):
        for rot in ('', ', ror #8', ', ror #16', ', ror #24'):
            c.add('%s r0, r1, r2%s' % (op, rot), 'r1=80ff7f01 r2=01ff0180', 'r1=ffff0001 r2=ffff8000')
    c.comment('pkhbt / pkhtb')
    for n in (0, 8, 16, 31):
        c.add('pkhbt r0, r1, r2, lsl #%d' % n)
    for n in (8, 16, 31, 32):
        c.add('pkhtb r0, r1, r2, asr #%d' % n)
    c.add('pkhbt r0, r1, r2')
    c.add('pkhtb r0, r1, r2')
    c.comment('bit fields')
    for lsb, width in ((0, 1), (0, 8), (4, 8), (3, 12), (16, 16), (31, 1), (0, 32), (5, 27), (1, 31)):
        c.add('bfi r0, r1, #%d, #%d' % (lsb, width))
        c.add('bfc r0, #%d, #%d' % (lsb, width))
        c.add('ubfx r0, r1, #%d, #%d' % (lsb, width))
        c.add('sbfx r0, r1, #%d, #%d' % (lsb, width))
    c.comment('reverse, count')
    for op in ('rev', 'rev16', 'revsh', 'rbit', 'clz'):
        c.add('%s r0, r1' % op, 'r1=0', 'r1=1', 'r1=80000000', 'r1=ffffffff', 'r1=00ff00ff', 'r1=12345678')
    c.comment('crc32')
    for op in ('crc32b', 'crc32h', 'crc32w', 'crc32cb', 'crc32ch', 'crc32cw'):
        c.add('%s r0, r1, r2' % op, 'r1=0 r2=0', 'r1=ffffffff r2=12345678', 'r1=12345678 r2=abcdef01')
    if not thumb:
        c.comment('the conditions')
        for cond in CONDS:
            for t in ('qadd r0, r1, r2', 'ssat r0, #8, r1', 'usat16 r0, #5, r1', 'sadd16 r0, r1, r2',
                      'uqsub8 r0, r1, r2', 'shasx r0, r1, r2', 'sel r0, r1, r2', 'sxtab r0, r1, r2, ror #8',
                      'uxtb16 r0, r1', 'pkhbt r0, r1, r2, lsl #4', 'bfi r0, r1, #4, #8', 'ubfx r0, r1, #3, #9',
                      'rev r0, r1', 'rbit r0, r1', 'clz r0, r1'):
                c.add(cond_twin(t, cond))
    c.write()


