# The immediates: plain, rotated (the carry out of ARMExpandImm_C), with bit 31
A32_IMMS = ['#0', '#1', '#0xff', '#0x3fc', '#0xff00', '#0x80000000', '#0xff000000', '#0xc0000034',
            '#0x1fc00000', '#0xf000000f']
SHIFTS_IMM = ['lsl #1', 'lsl #31', 'lsr #1', 'lsr #16', 'lsr #31', 'lsr #32', 'asr #1', 'asr #31', 'asr #32',
              'ror #1', 'ror #16', 'ror #31', 'rrx']
SHIFTS_REG = ['lsl r3', 'lsr r3', 'asr r3', 'ror r3']
# The values of the shift amount register: 0, 1, 31, 32, 33, 255, 256 (only the low byte counts)
AMOUNTS = ['r3=0', 'r3=1', 'r3=1f', 'r3=20', 'r3=21', 'r3=ff', 'r3=100', 'r3=101']


def gen_a32_dp():
    c = Corpus('a32_dp.s', 'A32 data processing: the shifter operand, the carry out, the flag setting forms')
    ops3 = ['and', 'eor', 'sub', 'rsb', 'add', 'adc', 'sbc', 'rsc', 'orr', 'bic']
    for op in ops3:
        for s in ('', 's'):
            c.comment('%s%s' % (op, s))
            c.add('%s%s r0, r1, r2' % (op, s), C0, C1)
            c.add('%s%s r0, r1, r0' % (op, s))
            c.add('%s%s r0, r0, r2' % (op, s))
            for imm in A32_IMMS:
                c.add('%s%s r0, r1, %s' % (op, s, imm), C0, C1)
            for sh in SHIFTS_IMM:
                c.add('%s%s r0, r1, r2, %s' % (op, s, sh), C0, C1)
            for sh in SHIFTS_REG:
                c.add('%s%s r0, r1, r2, %s' % (op, s, sh), *[a + ' ' + C1.replace('apsr=', 'apsr=') for a in AMOUNTS])
    # the compares and the tests always set the flags
    for op in ('tst', 'teq', 'cmp', 'cmn'):
        c.comment(op)
        c.add('%s r1, r2' % op, C0, C1)
        for imm in A32_IMMS:
            c.add('%s r1, %s' % (op, imm), C0, C1)
        for sh in SHIFTS_IMM:
            c.add('%s r1, r2, %s' % (op, sh), C0, C1)
        for sh in SHIFTS_REG:
            c.add('%s r1, r2, %s' % (op, sh), *AMOUNTS)
    for op in ('mov', 'mvn'):
        for s in ('', 's'):
            c.comment('%s%s' % (op, s))
            c.add('%s%s r0, r1' % (op, s), C0, C1)
            for imm in A32_IMMS:
                c.add('%s%s r0, %s' % (op, s, imm), C0, C1)
            for sh in SHIFTS_IMM:
                c.add('%s%s r0, r1, %s' % (op, s, sh), C0, C1)
            for sh in SHIFTS_REG:
                c.add('%s%s r0, r1, %s' % (op, s, sh), *AMOUNTS)
    c.comment('the shift instructions (aliases of mov)')
    for op in ('lsl', 'lsr', 'asr', 'ror'):
        for s in ('', 's'):
            amounts = {'lsl': (1, 7, 31), 'lsr': (1, 7, 31, 32), 'asr': (1, 7, 31, 32), 'ror': (1, 7, 31)}[op]
            for n in amounts:
                c.add('%s%s r0, r1, #%d' % (op, s, n), C0, C1)
            c.add('%s%s r0, r1, r2' % (op, s), *AMOUNTS)
    for s in ('', 's'):
        c.add('rrx%s r0, r1' % s, C0, C1)
    c.comment('movw / movt')
    for imm in ('0', '1', '0x1234', '0xffff', '0x8000'):
        c.add('movw r0, #%s' % imm)
        c.add('movt r0, #%s' % imm)
    c.comment('the pc as an operand and as the destination')
    c.add('mov r0, pc')
    c.add('add r0, pc, #4')
    c.add('sub r0, pc, #4')
    c.add('add r0, pc, r1')
    c.add('add r0, r1, pc')
    c.add('cmp pc, r1')
    c.add('mov pc, r1', 'r1=20001', 'r1=20002', 'r1=20003', 'r1=20000')
    c.add('add pc, pc, #4')
    c.add('add pc, r1, r2')
    c.add('sub pc, r1, #8', 'r1=20003')
    c.add('orr pc, r1, #1', 'r1=30000')
    c.add('mvn pc, r1')
    c.add('lsl pc, r1, #1')
    # every instruction under every condition: a twin of the lines above
    c.comment('the conditions')
    for i, cond in enumerate(CONDS):
        c.add(cond_twin('add r0, r1, r2', cond))
        c.add(cond_twin('adds r0, r1, r2, lsl r3', cond))
        c.add(cond_twin('sub r0, r1, #0xff', cond))
        c.add(cond_twin('subs r0, r1, #1', cond))
        c.add(cond_twin('movs r0, r1, ror #3', cond))
        c.add(cond_twin('mvn r0, #0x80000000', cond))
        c.add(cond_twin('orrs r0, r1, #0x80000000', cond))
        c.add(cond_twin('cmp r1, r2', cond))
        c.add(cond_twin('tst r1, #0xff00', cond))
        c.add(cond_twin('adc r0, r1, r2, rrx', cond))
        c.add(cond_twin('rsc r0, r1, r2', cond))
        c.add(cond_twin('lsl r0, r1, #4', cond))
        c.add(cond_twin('movw r0, #0x1234', cond))
        c.add(cond_twin('movt r0, #0x1234', cond))
    c.write()


