def gen_a32_mul():
    c = Corpus('a32_mul.s', 'A32 multiplies, divides and multiply accumulates')
    for s in ('', 's'):
        c.add('mul%s r0, r1, r2' % s)
        c.add('mul%s r0, r0, r2' % s)
        c.add('mla%s r0, r1, r2, r3' % s)
        c.add('umull%s r0, r1, r2, r3' % s)
        c.add('smull%s r0, r1, r2, r3' % s)
        c.add('umlal%s r0, r1, r2, r3' % s)
        c.add('smlal%s r0, r1, r2, r3' % s)
    c.add('mls r0, r1, r2, r3')
    c.add('umaal r0, r1, r2, r3')
    c.comment('halfword multiplies (Q on the accumulate overflow)')
    big = ['r1=7fff7fff r2=7fff7fff r3=7fffffff', 'r1=80008000 r2=80008000 r3=80000000',
           'r1=ffff8000 r2=80007fff r3=ffffffff', 'r1=12345678 r2=9abcdef0 r3=7ff00000']
    for xy in ('bb', 'bt', 'tb', 'tt'):
        c.add('smul%s r0, r1, r2' % xy, *big)
        c.add('smla%s r0, r1, r2, r3' % xy, *big)
        c.add('smlal%s r0, r1, r2, r3' % xy, *big)
    for y in ('b', 't'):
        c.add('smulw%s r0, r1, r2' % y, *big)
        c.add('smlaw%s r0, r1, r2, r3' % y, *big)
    c.comment('dual multiplies')
    for x in ('', 'x'):
        c.add('smuad%s r0, r1, r2' % x, *big)
        c.add('smusd%s r0, r1, r2' % x, *big)
        c.add('smlad%s r0, r1, r2, r3' % x, *big)
        c.add('smlsd%s r0, r1, r2, r3' % x, *big)
        c.add('smlald%s r0, r1, r2, r3' % x, *big)
        c.add('smlsld%s r0, r1, r2, r3' % x, *big)
    c.comment('most significant word multiplies')
    for r in ('', 'r'):
        c.add('smmul%s r0, r1, r2' % r, *big)
        c.add('smmla%s r0, r1, r2, r3' % r, *big)
        c.add('smmls%s r0, r1, r2, r3' % r, *big)
    c.add('usad8 r0, r1, r2')
    c.add('usada8 r0, r1, r2, r3')
    c.comment('divide: by zero gives 0, the minimum / -1 is the minimum')
    for op in ('sdiv', 'udiv'):
        c.add('%s r0, r1, r2' % op, 'r2=0', 'r1=80000000 r2=ffffffff', 'r1=ffffffff r2=2', 'r1=7 r2=ffffffff')
    c.comment('the conditions')
    for cond in CONDS:
        for t in ('mul r0, r1, r2', 'muls r0, r1, r2', 'mla r0, r1, r2, r3', 'umull r0, r1, r2, r3',
                  'smlalbb r0, r1, r2, r3', 'smlabt r0, r1, r2, r3', 'smuadx r0, r1, r2',
                  'smmlar r0, r1, r2, r3', 'sdiv r0, r1, r2', 'usada8 r0, r1, r2, r3'):
            c.add(cond_twin(t, cond))
    c.write()


