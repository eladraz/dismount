def gen_a32_mem():
    c = Corpus('a32_mem.s', 'A32 loads and stores: every addressing mode, the multiple registers, the exclusives')
    # the word and byte accesses (mode 2)
    for op in ('ldr', 'str', 'ldrb', 'strb'):
        c.comment(op)
        for mode in ('[r4]', '[r4, #0]', '[r4, #4]', '[r4, #-4]', '[r4, #4095]', '[r4, #-4095]',
                     '[r4, #8]!', '[r4, #-8]!', '[r4], #8', '[r4], #-8', '[r4], #4095',
                     '[r4, r5]', '[r4, -r5]', '[r4, r5, lsl #2]', '[r4, -r5, lsl #1]', '[r4, r5, lsr #2]',
                     '[r4, r5, lsr #32]', '[r4, r5, asr #4]', '[r4, r5, asr #32]', '[r4, r5, ror #4]',
                     '[r4, r5, rrx]', '[r4, r5]!', '[r4, -r5]!', '[r4, r5, lsl #3]!', '[r4], r5', '[r4], -r5',
                     '[r4], r5, lsl #2', '[r4], r5, lsr #3', '[r4], -r5, asr #1', '[r4], r5, ror #2', '[r4], r5, rrx'):
            c.add('%s r0, %s' % (op, mode))
        c.add('%s r4, [r4, #4]' % op)
        c.add('%s r0, [r4, r4]' % op)
    for op in ('ldr', 'ldrb'):
        c.add('%s r0, [pc, #8]' % op)
        c.add('%s r0, [pc, #-8]' % op)
        c.add('%s r0, [sp]' % op)
        c.add('%s r0, [sp, #12]' % op)
    c.add('str r0, [sp, #-4]!')
    c.add('str pc, [r4]')
    c.add('ldr pc, [r4]', 'mem=20004000:01000000', 'mem=20004000:02000000', 'mem=20004000:03000000')
    c.add('ldr pc, [sp], #4')
    c.add('ldr lr, [sp], #4')
    # the halfword and signed accesses (mode 3)
    for op in ('ldrh', 'strh', 'ldrsb', 'ldrsh'):
        c.comment(op)
        for mode in ('[r4]', '[r4, #2]', '[r4, #-2]', '[r4, #255]', '[r4, #-255]', '[r4, #6]!', '[r4, #-6]!',
                     '[r4], #6', '[r4], #-6', '[r4, r5]', '[r4, -r5]', '[r4, r5]!', '[r4, -r5]!', '[r4], r5',
                     '[r4], -r5'):
            c.add('%s r0, %s' % (op, mode))
        c.add('%s r4, [r4, #2]' % op)
    for op in ('ldrh', 'ldrsb', 'ldrsh'):
        c.add('%s r0, [pc, #8]' % op)
    c.comment('double words')
    for op in ('ldrd', 'strd'):
        for mode in ('[r4]', '[r4, #8]', '[r4, #-8]', '[r4, #255]', '[r4, #8]!', '[r4], #8', '[r4], #-8',
                     '[r4, r5]', '[r4, -r5]', '[r4, r5]!', '[r4], r5'):
            c.add('%s r2, r3, %s' % (op, mode))
        c.add('%s r4, r5, [sp, #8]' % op)
    c.comment('the unprivileged accesses')
    for op in ('ldrt', 'strt', 'ldrbt', 'strbt'):
        c.add('%s r0, [r4]' % op)
        c.add('%s r0, [r4], #4' % op)
        c.add('%s r0, [r4], #-4' % op)
        c.add('%s r0, [r4], r5' % op)
        c.add('%s r0, [r4], -r5, lsl #2' % op)
    for op in ('ldrht', 'strht', 'ldrsbt', 'ldrsht'):
        c.add('%s r0, [r4], #6' % op)
        c.add('%s r0, [r4], #-6' % op)
        c.add('%s r0, [r4], r5' % op)
    c.comment('acquire / release')
    for op in ('lda', 'ldab', 'ldah', 'stl', 'stlb', 'stlh'):
        c.add('%s r0, [r4]' % op)
    c.comment('load and store multiple')
    lists = ['{r0}', '{r0, r1}', '{r0-r3}', '{r1, r3, r5, r7}', '{r0, r2, r5, lr}', '{r0-r3, r8-r12}', '{r5, r6, r7, r8}']
    for op in ('ldm', 'ldmia', 'ldmib', 'ldmda', 'ldmdb', 'stm', 'stmia', 'stmib', 'stmda', 'stmdb'):
        for wb in ('', '!'):
            for lst in lists[:4]:
                c.add('%s r4%s, %s' % (op, wb, lst))
            c.add('%s r4%s, %s' % (op, wb, lists[4]))
        c.add('%s sp!, {r0, r1}' % op)
    for lst in ('{r0, pc}', '{pc}', '{r5, r6, pc}', '{r0-r3, pc}'):
        c.add('ldm r4!, %s' % lst, 'mem=20004000:01000000', 'mem=20004000:03000000')
        c.add('ldmdb r4, %s' % lst)
    c.add('stm r4, {r0, pc}')
    c.add('stmdb r4!, {r0, pc}')
    c.add('ldm r4, {r4, r5}')
    c.add('ldm r4!, {r1, r2}')
    c.add('stm r4!, {r4, r5}')
    for lst in lists:
        c.add('push %s' % lst)
