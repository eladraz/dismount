#!/usr/bin/env python3
"""Write the AArch32 integer corpus files of the semantics tests (tests/arm/semantics/corpus):

    a32_dp.s    a32_mul.s    a32_dsp.s    a32_mem.s    a32_ctl.s
    t32_dp.s    t32_dsp.s    t32_mem.s    t32_ctl.s    t32_it.s

Every mnemonic of the A32 / T32 integer table (gArmSemanticTable) with every operand shape and
addressing mode, the data processing with the shifter operand and its carry out (every shift type
and amount, the register shifts, the rotated immediates), the flag setting forms, the
multiplies, the saturating and the parallel arithmetic, the loads and stores, and the conditions
of A32 and the IT blocks of T32. The lines get directed `@state:` where the random states do not
reach an interesting case (carry in, the saturation limits, the GE flags).

    gen_corpus_aarch32_int.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import armlib

OUT = os.path.join(armlib.REPO, 'tests', 'arm', 'semantics', 'corpus')

CONDS = ['eq', 'ne', 'cs', 'cc', 'mi', 'pl', 'vs', 'vc', 'hi', 'ls', 'ge', 'lt', 'gt', 'le']
# The flags NZCV of the directed states: apsr bits 31-28
C0, C1 = 'apsr=00000000', 'apsr=20000000'
ALLFLAGS = ['apsr=00000000', 'apsr=20000000', 'apsr=40000000', 'apsr=60000000', 'apsr=80000000',
            'apsr=a0000000', 'apsr=c0000000', 'apsr=e0000000', 'apsr=10000000', 'apsr=30000000',
            'apsr=50000000', 'apsr=70000000', 'apsr=90000000', 'apsr=b0000000', 'apsr=d0000000',
            'apsr=f0000000']


class Corpus(object):
    def __init__(self, name, title):
        self.name = name
        self.lines = ['// %s' % title, '// GENERATED by tests/arm/tools/gen_corpus_aarch32_int.py']
        self.count = 0

    def comment(self, text):
        self.lines.append('// --- ' + text)

    def add(self, text, *states):
        line = text
        if states:
            line += '    // ' + ' '.join('@state: ' + s for s in states)
        self.lines.append(line)
        self.count += 1

    def write(self):
        with open(os.path.join(OUT, self.name), 'w') as f:
            f.write('\n'.join(self.lines) + '\n')
        print('%s: %d lines' % (self.name, self.count))


def cond_twin(text, cond):
    """The conditional spelling of an A32 instruction: the condition goes after the mnemonic (and
    after the s of the flag setting forms, the unified syntax)."""
    head, sep, rest = text.partition(' ')
    return head + cond + sep + rest


