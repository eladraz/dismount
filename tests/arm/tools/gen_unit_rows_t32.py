#!/usr/bin/env python3
"""Generate tests/arm/AArch32TestRows_T32.inc, the T32 rows of
tests/TestArmAArch32Disassembler.cpp: { address, size, encoding, itState,
"text" } for a few shapes of every mnemonic of the T32 corpus (the it blocks
too: the it row with the state 0, then its instructions with the state which
applies to each one), and the encodings which have to be invalid. The texts are
what objdump prints, so the unit test pins the LLVM syntax.

    gen_unit_rows_t32.py [--per-mnemonic N]
"""
import argparse
import collections
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import armlib
import compat_t32
import fuzz_decode

OUTPUT = os.path.join(armlib.REPO, 'tests', 'arm', 'AArch32TestRows_T32.inc')
CORPUS = os.path.join(armlib.REPO, 'tests', 'arm', 'corpus', 't32')


def shape(text):
    return re.sub(r'\b([rsdq])\d+\b', r'\1N', re.sub(r'0x[0-9a-f]+|\d+', 'N', text))


def advance(state):
    return 0 if (state & 7) == 0 else ((state & 0xE0) | ((state << 1) & 0x1F))


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--per-mnemonic', type=int, default=3)
    args = parser.parse_args()

    lines = []
    for path in sorted(glob.glob(os.path.join(CORPUS, '*.s'))):
        for raw in open(path):
            if raw.startswith('//') or not raw.strip():
                continue
            lines.append(re.sub(r'\s*// @feature:.*$', '', raw.rstrip('\n')).strip())
    results = armlib.clang_assemble(lines, 't32')
    unit_lists = [compat_t32.split_units(data) for status, data in results if status == 'ok']
    texts, addresses = compat_t32.objdump_lines(unit_lists)
    names = set(r[5].split('.')[0] for r in armlib.entries('t32'))
    picked = collections.defaultdict(list)
    for units, text, address in zip(unit_lists, texts, addresses):
        parts = text.split(' ; ')
        if len(units) != len(parts) or any(p == '<unknown>' for p in parts):
            continue
        is_block = len(units) > 1
        head = parts[1] if is_block else parts[0]
        key = ('it:' if is_block else '') + head.split(' ')[0].split('.')[0]
        shapes = [shape(t) for _, _, _, t in picked[key]]
        if len(picked[key]) < args.per_mnemonic and shape(text) not in shapes:
            picked[key].append((address, units, parts, text))

    rows = []
    for key in sorted(picked):
        for address, units, parts, text in picked[key]:
            state = 0
            offset = address
            for index, (unit, part) in enumerate(zip(units, parts)):
                size, value = unit
                rows.append((offset, size, value, state, part))
                if index == 0 and size == 2 and (value & 0xff00) == 0xbf00 and (value & 0xf) != 0:
                    state = value & 0xff
                    if (state >> 4) == 15:
                        state = (state & 0x0f) | 0xe0
                elif state:
                    state = advance(state)
                offset += size
    # Invalid encodings: random units which objdump says are unknown (the
    # ones which are valid vector instructions are not in this list)
    rng = armlib.seeded_rng(5)
    pool = []
    while len(pool) < 400:
        unit = armlib.t32_unit(rng.getrandbits(32))
        if not armlib.t32_is_it(unit):
            pool.append(unit)
    inv_texts, _ = armlib.objdump_unit_chunks(pool)
    invalid = [u for u, t in zip(pool, inv_texts) if t == '<unknown>'][:80]

    with open(OUTPUT, 'w') as f:
        f.write('// Generated by tests/arm/tools/gen_unit_rows_t32.py: the T32 rows of\n')
        f.write('// tests/TestArmAArch32Disassembler.cpp. { address, size, encoding, it state,\n')
        f.write('// text }: LLVM text. The it rows come in order, the it first (state 0).\n')
        f.write('#define AARCH32_T32_ROWS \\\n')
        for address, size, value, state, text in rows:
            f.write('    { 0x%x, %d, 0x%0*x, 0x%02x, "%s" }, \\\n' % (
                address, size, size * 2, value, state, text.replace('"', '\\"')))
        f.write('\n#define AARCH32_T32_INVALID \\\n')
        for size, value in invalid:
            f.write('    { 0x%0*x, %d, true }, \\\n' % (size * 2, value, size))
        f.write('\n')
    print('%d rows, %d invalid encodings' % (len(rows), len(invalid)))


if __name__ == '__main__':
    main()
