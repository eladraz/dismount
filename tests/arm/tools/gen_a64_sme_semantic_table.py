#!/usr/bin/env python3
"""Generate Source/dismount/proc/arm/Arm64SemanticTableSme.cpp, the semantic table of the A64 SME / SME2
instructions: one entry for every mnemonic of the SME encoding table
(Source/dismount/proc/arm/Arm64EncodingTableSme.cpp) with its classification (category, units,
properties). Every entry is lifted by liftArm64Sme() (Arm64SemanticLiftSme.cpp), which dispatches on the
mnemonic and the operands; the forms the lifters don't handle are OP_UNDEFINED.

    gen_a64_sme_semantic_table.py

Author: Elad Raz <e@eladraz.com>
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
TABLE = os.path.join(REPO, 'Source', 'dismount', 'proc', 'arm', 'Arm64EncodingTableSme.cpp')
OUTPUT = os.path.join(REPO, 'Source', 'dismount', 'proc', 'arm', 'Arm64SemanticTableSme.cpp')

MOVES = {'mova', 'mov', 'movaz', 'movt'}
# the vector length instructions (their encodings are in the SVE table, see ArmSemanticLifter::findEntry)
LENGTH = {'rdsvl', 'addsvl', 'addspl'}
LOADS = {'ld1b', 'ld1h', 'ld1w', 'ld1d', 'ld1q', 'ldr'}
STORES = {'st1b', 'st1h', 'st1w', 'st1d', 'st1q', 'str'}
OUTER = {'fmopa', 'fmops', 'bfmopa', 'bfmops', 'smopa', 'smops', 'umopa', 'umops', 'sumopa', 'sumops',
         'usmopa', 'usmops', 'bmopa', 'bmops', 'addha', 'addva', 'zero', 'stmopa', 'utmopa', 'sutmopa',
         'ustmopa', 'ftmopa', 'bftmopa'}
FLOAT = {'fadd', 'fsub', 'fmla', 'fmls', 'fmul', 'fmax', 'fmin', 'fmaxnm', 'fminnm', 'famax', 'famin',
         'fclamp', 'fscale', 'frinta', 'frintm', 'frintn', 'frintp', 'fdot', 'fvdot', 'fvdotb', 'fvdott',
         'fmlal', 'fmlsl', 'fmlall', 'bfadd', 'bfsub', 'bfmla', 'bfmls', 'bfmul', 'bfmax', 'bfmin',
         'bfmaxnm', 'bfminnm', 'bfclamp', 'bfscale', 'bfdot', 'bfvdot', 'bfmlal', 'bfmlsl'}
CONVERT = {'fcvt', 'fcvtl', 'fcvtn', 'fcvtzs', 'fcvtzu', 'scvtf', 'ucvtf', 'bfcvt', 'bfcvtn', 'sqcvt',
           'sqcvtn', 'sqcvtu', 'sqcvtun', 'uqcvt', 'uqcvtn', 'sqrshr', 'sqrshrn', 'sqrshru', 'sqrshrun',
           'uqrshr', 'uqrshrn', 'sunpk', 'uunpk', 'f1cvt', 'f1cvtl', 'f2cvt', 'f2cvtl', 'bf1cvt', 'bf1cvtl',
           'bf2cvt', 'bf2cvtl'}
PERMUTE = {'zip', 'uzp', 'sel', 'luti2', 'luti4', 'luti6'}


def classify(name):
    if name in LENGTH:
        return 'ARITHMETIC', 'U_(INTEGER_ALU)', ''
    if name in MOVES:
        return 'MOVE', 'U_(MATRIX)', ''
    if name in LOADS:
        return 'LOAD', 'U_(MATRIX) | U_(LOAD)', 'P_(READS_MEMORY) | P_(MAY_FAULT) | P_(PREDICATED)'
    if name in STORES:
        return 'STORE', 'U_(MATRIX) | U_(STORE)', 'P_(WRITES_MEMORY) | P_(MAY_FAULT) | P_(PREDICATED)'
    if name in OUTER or name.endswith(('mopa', 'mops', 'mop4a', 'mop4s')):
        return 'MATRIX', 'U_(MATRIX)', 'P_(PREDICATED)' if 'mop4' not in name and name != 'zero' else ''
    if name in FLOAT:
        return 'MATRIX', 'U_(MATRIX) | U_(VECTOR_FLOAT)', ''
    if name in CONVERT:
        return 'CONVERT', 'U_(VECTOR_FLOAT) | U_(FLOAT_CONVERT)', ''
    if name in PERMUTE:
        return 'VECTOR_PERMUTE', 'U_(VECTOR_PERMUTE)', ''
    return 'MATRIX', 'U_(MATRIX) | U_(VECTOR_INTEGER)', ''


def main():
    text = open(TABLE).read()
    names = []
    for m in re.finditer(r'\n    E\("([a-z0-9_]+)", ', text):
        if m.group(1) not in names:
            names.append(m.group(1))
    for extra in sorted(LENGTH):
        if extra not in names:
            names.append(extra)
    out = ['''/*
 * Arm64SemanticTableSme.cpp
 *
 * Implementation file
 *
 * The semantic table of the A64 SME and SME2 instructions (see ArmSemantics.h): the mnemonics of
 * gArm64SmeEncodingTable with their classification. Every entry is lifted by liftArm64Sme()
 * (Arm64SemanticLiftSme.cpp), which dispatches on the mnemonic and the operands (the aliases
 * mov / mova are one lifter); the forms which are not lifted (see ArmFeatures.cpp) are
 * OP_UNDEFINED.
 *
 * GENERATED by tests/arm/tools/gen_a64_sme_semantic_table.py: edit the generator, not this
 * file.
 *
 * Author: Elad Raz <e@eladraz.com>
 */
#include "xStl/types.h"
#include "dismount/semantics/SemanticTemplate.h"
#include "dismount/semantics/ArchitectureDescription.h"
#include "dismount/semantics/OpcodeClassification.h"
#include "dismount/proc/arm/ArmSemantics.h"
#include "dismount/proc/arm/Arm64SemanticSme.h"

namespace armdis {

namespace {

// An entry: the mnemonic, the category, the units, the properties, the flags read and written
#define A64(name, category, units, properties, read, written) \\
    { ArmSemanticEntry::ANY_OPERANDS_COUNT, \\
      { name, NULL, 0, OpcodeClassification::CATEGORY_##category, units, properties, \\
        read, written, 0, 0 }, \\
      liftArm64Sme, 0, 0, 0, 0 }
#define U_(x) OpcodeClassification::UNIT_##x
#define P_(x) OpcodeClassification::PROPERTY_##x

} // namespace

const ArmSemanticEntry gArm64SmeSemanticTable[] =
{''']
    for n in names:
        cat, units, props = classify(n)
        out.append('    A64("%s", %s, %s, %s, 0, 0),' % (n, cat, units, props or '0'))
    out.append('    { 0, { NULL, NULL, 0, 0, 0, 0, 0, 0, 0, 0 }, NULL, 0, 0, 0, 0 }')
    out.append('};')
    out.append('')
    out.append('} // namespace armdis')
    open(OUTPUT, 'w').write('\n'.join(out) + '\n')
    print('%d mnemonics' % len(names))


if __name__ == '__main__':
    main()
