#!/usr/bin/env python3
"""Generate tests/arm/Arm64SveSemanticRows.inc, the rows of tests/TestArm64SemanticsSve.cpp: an
A64 SVE instruction, a start state and the state it must leave, at the vector lengths 128, 256 and
512. The expected values come from the independent models of the pseudocode of the Arm ARM in
tests/arm/tools/sve_model_*.py (see sve_model.py), not from running dismount.

The words are assembled by clang (tests/arm/semantics/armasm.py).

    gen_sve_semantic_rows.py
"""
import glob
import importlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, '..', 'semantics'))
import armlib
import armasm
import sve_model
import cliteral

OUTPUT = os.path.join(armlib.REPO, 'tests', 'arm', 'Arm64SveSemanticRows.inc')


def runs(memory):
    """The contiguous byte runs of a memory dict, as "addr:hex,addr:hex"."""
    out = []
    addresses = sorted(memory)
    i = 0
    while i < len(addresses):
        j = i
        while j + 1 < len(addresses) and addresses[j + 1] == addresses[j] + 1:
            j += 1
        out.append('%x:%s' % (addresses[i], ''.join('%02x' % memory[a] for a in addresses[i:j + 1])))
        i = j + 1
    return ','.join(out)


def main():
    rows = []
    for path in sorted(glob.glob(os.path.join(HERE, 'sve_model_*.py'))):
        module = importlib.import_module(os.path.basename(path)[:-3])
        rows += [(os.path.basename(path)[:-3], r) for r in module.rows()]
    texts = [r.text for _, r in rows]
    assembled = armasm.assemble('a64', texts)
    lines = []
    for (module, row), (hexb, error) in zip(rows, assembled):
        if error is not None:
            sys.stderr.write('%s: %s: %s\n' % (module, row.text, error))
            sys.exit(1)
        data = bytes.fromhex(hexb)
        words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
        final = row.start.copy()
        row.model(final)
        setup = sve_model.tokens_of(row.start, row.vl)
        if row.start.mem:
            setup.append('mem=' + runs(row.start.mem))
        expected = sve_model.tokens_of(final, row.vl, row.start)
        changed = dict((a, v) for a, v in final.mem.items() if row.start.mem.get(a, 0) != v)
        if changed:
            expected.append('mem=' + runs(changed))
        if final.exit != 'fall':
            expected.append('exit=' + final.exit)
        lines.append('    { {%s}, %d, "%s", %d, %s, %s },' % (
            ', '.join('0x%08x' % w for w in words + [0] * (2 - len(words))), len(words),
            row.text.replace('"', '\\"'), row.vl, cliteral.literal(' '.join(setup)),
            cliteral.literal(' '.join(expected))))
    with open(OUTPUT, 'w') as f:
        f.write('// Generated by tests/arm/tools/gen_sve_semantic_rows.py: the rows of tests/TestArm64SemanticsSve.cpp.\n'
                '// { {words}, count, "text", vl, "setup", "expected" }\n'
                '// The rows are included inside the initializer of the table: a macro of\n'
                '// the whole table is too big for MSVC (C1060)\n')
        f.write('\n'.join(lines) + '\n')
    print('%s: %d rows' % (OUTPUT, len(lines)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
