#!/usr/bin/env python3
"""Generate tests/arm/AArch32TestRows_A32.inc, the rows of
tests/TestArmAArch32Disassembler.cpp for A32: {address, word, "text"} for a
few shapes of every mnemonic of the A32 corpus, and the words which have to be
invalid. The texts are what objdump prints for the words, so the unit test
pins the LLVM syntax.

    gen_unit_rows_aarch32.py [--per-mnemonic N]
"""
import argparse
import collections
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import armlib
import gen_corpus_aarch32

OUTPUT = os.path.join(armlib.REPO, 'tests', 'arm', 'AArch32TestRows_A32.inc')
CORPUS = os.path.join(armlib.REPO, 'tests', 'arm', 'corpus', 'a32')


def shape(text):
    """The shape of a text: the numbers and the register numbers removed, so
    the rows differ by form and not by value."""
    return re.sub(r'\b([rsdq])\d+\b', r'\1N', re.sub(r'0x[0-9a-f]+|\d+', 'N', text))


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--per-mnemonic', type=int, default=3)
    args = parser.parse_args()

    lines = []
    for path in sorted(glob.glob(os.path.join(CORPUS, '*.s'))):
        for raw in open(path):
            if raw.startswith('//') or not raw.strip():
                continue
            lines.append(re.sub(r'\s*// @feature:.*$', '', raw.rstrip('\n')).strip())
    results = armlib.clang_assemble(lines, 'a32')
    words = []
    for line, (status, data) in zip(lines, results):
        if status == 'ok':
            words.append(armlib.hex_bytes_to_word(data))
    texts, addresses = armlib.objdump_chunks(words, 'a32')
    names = gen_corpus_aarch32.base_names(armlib.entries('a32'))
    picked = collections.defaultdict(list)
    for word, address, text in zip(words, addresses, texts):
        if text == '<unknown>':
            continue
        mnemonic = gen_corpus_aarch32.key_of(text, names)
        shapes = [shape(t) for _, _, t in picked[mnemonic]]
        if len(picked[mnemonic]) < args.per_mnemonic and shape(text) not in shapes:
            picked[mnemonic].append((address, word, text))
    rows = []
    for mnemonic in sorted(picked):
        rows.extend(picked[mnemonic])

    rng = armlib.seeded_rng(5)
    invalid = [rng.getrandbits(32) for _ in range(200)]
    inv_texts = armlib.objdump_words(invalid, 'a32')
    invalid = [w for w, t in zip(invalid, inv_texts) if t == '<unknown>'][:60]

    with open(OUTPUT, 'w') as f:
        f.write('// Generated by tests/arm/tools/gen_unit_rows_aarch32.py: the A32 rows of\n')
        f.write('// tests/TestArmAArch32Disassembler.cpp. {address, word, text}: LLVM text.\n')
        f.write('#define AARCH32_A32_ROWS \\\n')
        for address, word, text in rows:
            f.write('    { 0x%x, 0x%08x, "%s" }, \\\n' % (address, word, text.replace('"', '\\"')))
        f.write('\n#define AARCH32_A32_INVALID \\\n')
        for w in invalid:
            f.write('    0x%08x, \\\n' % w)
        f.write('\n')
    print('%d rows, %d invalid words' % (len(rows), len(invalid)))


if __name__ == '__main__':
    main()
