#!/usr/bin/env python3
"""
Generates tests/semantics/corpus/baseline16.asm, baseline.asm (32 bit) and
baseline64.asm: the directed cases of the baseline instructions of the semantics
tests (dismount IR vs. Unicorn): cmovcc (every condition and mnemonic alias,
true and false, and the zero extension of a 32 bit destination of 64 bit mode
when the condition is false), ud2 / ud1 / ud0, int1, salc, pause, endbr32 /
endbr64, popcnt / lzcnt / tzcnt (the zero and the single bit sources, the flags
that are cleared) and movbe.

  python3 tests/semantics/tools/gen_baseline.py

The states (registers, flags) are drawn by run_semantics.py; a line with
`; @state: rax=.. rcx=..` is added to its random states with those registers.
"""
import os

DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'corpus')

# The mnemonics of the conditions, in the order of the condition code (0F 40 + cc)
CONDITIONS = [
    ['o'], ['no'], ['b', 'c', 'nae'], ['ae', 'nb', 'nc'], ['z', 'e'], ['nz', 'ne'],
    ['be', 'na'], ['a', 'nbe'], ['s'], ['ns'], ['p', 'pe'], ['np', 'po'],
    ['l', 'nge'], ['ge', 'nl'], ['le', 'ng'], ['g', 'nle'],
]
# Flags: CF PF AF ZF SF OF, each alone, SF with OF, all of them, none of them
FLAG_STATES = [0x2, 0x3, 0x6, 0x12, 0x42, 0x82, 0x802, 0x882, 0x8d7]


def state(**regs):
    return ' @state: ' + ' '.join('%s=%x' % (k, v) for k, v in regs.items())


def flag_states(regs):
    return ''.join(state(eflags=f, **regs) for f in FLAG_STATES)


class Corpus:
    def __init__(self, bits, name, title):
        self.bits = bits
        self.name = name
        self.lines = [
            '; %s for the semantics tests (dismount IR vs. Unicorn), bits %d' % (title, bits),
            '; GENERATED by tests/semantics/tools/gen_baseline.py',
            '; Same format as tests/ia32/corpus. The states (registers, flags) are drawn by run_semantics.py;',
            '; "; @state: eax=.. ebx=.." adds a state with those registers.',
            '; @file-feature: i386',
            'bits %d' % bits,
        ]

    def section(self, title):
        self.lines.append('')
        self.lines.append('; --- ' + title)

    def emit(self, text, states=''):
        self.lines.append(text + ('  ;' + states if states else ''))

    def write(self):
        with open(os.path.join(DIR, self.name), 'w') as f:
            f.write('\n'.join(self.lines) + '\n')


def conditional_moves(c, regs, memory):
    """regs: tuples (dst16, src16, dst32, src32, dst64, src64) (the 64 bit names are None
    outside the 64 bit mode); memory: the base register of the memory operands."""
    c.section('cmovcc: every condition and every alias, the condition true and false')
    for names in CONDITIONS:
        for name in names:
            for (d16, s16, d32, s32, d64, s64) in regs:
                if d64 is not None:
                    # The upper half of the destination is set: a 32 bit destination is
                    # zero extended whether the condition holds or not
                    values = {d64: 0xffffffffffffffff, s64: 0x0123456789abcdef}
                else:
                    values = {d32: 0xffffffff, s32: 0x12345678}
                c.emit('cmov%s %s, %s' % (name, d16, s16), flag_states(values))
                c.emit('cmov%s %s, %s' % (name, d32, s32), flag_states(values))
                if d64 is not None:
                    c.emit('cmov%s %s, %s' % (name, d64, s64), flag_states(values))
            d16, d32, d64 = regs[0][0], regs[0][2], regs[0][4]
            c.emit('cmov%s %s, [%s]' % (name, d16, memory), flag_states({}))
            c.emit('cmov%s %s, [%s]' % (name, d32, memory), flag_states({}))
            if d64 is not None:
                c.emit('cmov%s %s, [%s]' % (name, d64, memory), flag_states({}))


def undefined_instructions(c, memory):
    c.section('ud2, ud1, ud0 and int1 raise the exceptions; the operands are not accessed')
    c.emit('ud2')
    for name in ('ud1', 'ud0'):
        c.emit('%s eax, ecx' % name)
        c.emit('%s eax, [%s]' % (name, memory))
        c.emit('%s ax, cx' % name)
    c.emit('int1')
    c.emit('icebp')


def nops(c):
    c.section('pause, endbr32 and endbr64 are nops')
    c.emit('pause')
    c.emit('endbr32')
    c.emit('endbr64')


def bit_counts(c, bits, memory):
    c.section('popcnt, lzcnt, tzcnt: the zero source, single bits, all ones, the flags cleared / set')
    # The register names of each operand size: the destination and the source, and the
    # full register which holds them
    sizes = [(16, 'ax', 'bx'), (32, 'eax', 'ebx')]
    full = ('eax', 'ebx') if bits < 64 else ('rax', 'rbx')
    if bits == 64:
        sizes.append((64, 'rax', 'rbx'))
    ones = (1 << bits) - 1 if bits < 64 else (1 << 64) - 1
    for op in ('popcnt', 'lzcnt', 'tzcnt'):
        for width, dst, src in sizes:
            mask = (1 << width) - 1
            values = [0, 1, 1 << (width - 1), mask, 1 << (width // 2), 0x5a5a5a5a5a5a5a5a & mask]
            states = ''
            for v in values:
                # The upper bits of the registers are set: a source reads only the low bits, a 16
                # bit destination keeps the upper bits and a 32 bit one of 64 bit mode clears them
                for f in (0x2, 0x8d7):
                    states += state(eflags=f, **{full[1]: v | (ones & ~mask), full[0]: ones})
            c.emit('%s %s, %s' % (op, dst, src), states)
        c.emit('%s ax, [%s]' % (op, memory))
        c.emit('%s eax, [%s]' % (op, memory))
        if bits == 64:
            c.emit('%s rax, [%s]' % (op, memory))
            c.emit('%s r9, r10' % op)
            c.emit('%s r9d, r10d' % op)
            c.emit('%s r9w, r10w' % op)


def byte_swaps(c, regs16, regs32, regs64, memory):
    c.section('movbe: loads and stores of 2, 4 and 8 bytes, byte reversed')
    for r in regs16:
        c.emit('movbe %s, [%s]' % (r, memory))
        c.emit('movbe [%s], %s' % (memory, r))
    for r in regs32:
        c.emit('movbe %s, [%s]' % (r, memory))
        c.emit('movbe [%s], %s' % (memory, r))
    for r in regs64:
        c.emit('movbe %s, [%s]' % (r, memory))
        c.emit('movbe [%s], %s' % (memory, r))


def main():
    # 16 bit mode
    c = Corpus(16, 'baseline16.asm', 'Directed cases of the baseline instructions')
    conditional_moves(c, [('ax', 'bx', 'eax', 'ebx', None, None), ('cx', 'dx', 'ecx', 'edx', None, None)], 'si')
    undefined_instructions(c, 'bx')
    c.section('salc: al = carry ? 0xff : 0')
    c.emit('salc', flag_states({'eax': 0x12345678}))
    nops(c)
    bit_counts(c, 16, 'si')
    byte_swaps(c, ['ax', 'dx'], ['eax', 'edx'], [], 'si')
    c.write()

    # 32 bit mode
    c = Corpus(32, 'baseline.asm', 'Directed cases of the baseline instructions')
    conditional_moves(c, [('ax', 'bx', 'eax', 'ebx', None, None), ('cx', 'dx', 'ecx', 'edx', None, None)], 'esi')
    undefined_instructions(c, 'ebx')
    c.section('salc: al = carry ? 0xff : 0')
    c.emit('salc', flag_states({'eax': 0x12345678}))
    nops(c)
    bit_counts(c, 32, 'esi')
    byte_swaps(c, ['ax', 'dx'], ['eax', 'edx'], [], 'esi')
    c.write()

    # 64 bit mode
    c = Corpus(64, 'baseline64.asm', 'Directed cases of the baseline instructions')
    conditional_moves(c, [('ax', 'bx', 'eax', 'ebx', 'rax', 'rbx'), ('r9w', 'r10w', 'r9d', 'r10d', 'r9', 'r10')], 'rsi')
    undefined_instructions(c, 'rbx')
    nops(c)
    bit_counts(c, 64, 'rsi')
    byte_swaps(c, ['ax', 'r9w'], ['eax', 'r9d'], ['rax', 'r9'], 'rsi')
    c.write()


if __name__ == '__main__':
    main()
