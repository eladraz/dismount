#ifndef __TBA_DISMOUNT_PROC_ARM_ARMOPERANDCODECINTERNAL_H
#define __TBA_DISMOUNT_PROC_ARM_ARMOPERANDCODECINTERNAL_H

/*
 * ArmOperandCodecInternal.h
 *
 * The parts of ArmOperandCodec which are split per area of the instruction
 * sets, so the areas can be filled independently: ArmOperandCodec.cpp
 * dispatches by the kind of the spec to the functions of the area which owns
 * it. Not a public header: use ArmOperandCodec.h.
 *
 * To add an area (A32, Simd, Sve, Sme): write ArmOperandCodec<Area>.cpp with
 * a decode and an encode function of this signature, and add its kinds to
 * the switches of ArmOperandCodec::decode() and encode().
 *
 * Author: Elad Raz <e@eladraz.com>
 */
#include "xStl/types.h"
#include "dismount/proc/arm/ArmOperandCodec.h"

namespace armdis {

/*
 * The area functions. They have the contract of ArmOperandCodec::decode() and
 * encode() for the kinds of their area
 */
// ArmOperandCodecA64.cpp: the A64 kinds (and the general purpose registers
// of A64)
bool decodeA64(const ArmOperandSpec& spec,
               uint32 encoding,
               const ArmCodecContext& context,
               ArmDecodedOperand& operand);
bool encodeA64(const ArmOperandSpec& spec,
               const ArmDecodedOperand& operand,
               const ArmCodecContext& context,
               uint32& encoding);

// ArmOperandCodecSimd.cpp: the kinds of the scalar floating point, Advanced
// SIMD and cryptographic instructions of A64. isSimdSpec() tells whether a
// spec is of this area (the vector kinds, the new schemes of the scalar
// registers and of the memory addressing)
bool isSimdSpec(const ArmOperandSpec& spec);
bool decodeSimd(const ArmOperandSpec& spec,
                uint32 encoding,
                const ArmCodecContext& context,
                ArmDecodedOperand& operand);
bool encodeSimd(const ArmOperandSpec& spec,
                const ArmDecodedOperand& operand,
                const ArmCodecContext& context,
                uint32& encoding);
// For the assembler, which compares the operands of the text with the ones
// that its bits decode to: true if the text names the arrangement, the
// element, the list and the post index that the bits decode to
bool isSameSimdOperand(const ArmDecodedOperand& parsed,
                       const ArmDecodedOperand& decoded);
// True if register id 'next' follows 'previous' in a register list (the
// registers wrap around: v31, v0)
bool isConsecutiveRegister(uint previous, uint next);

// ArmOperandCodecA32.cpp: the AArch32 kinds. TODO: only the general purpose
// registers are implemented
bool decodeA32(const ArmOperandSpec& spec,
               uint32 encoding,
               const ArmCodecContext& context,
               ArmDecodedOperand& operand);
bool encodeA32(const ArmOperandSpec& spec,
               const ArmDecodedOperand& operand,
               const ArmCodecContext& context,
               uint32& encoding);

// ArmOperandCodecSve.cpp: the SVE kinds (ARM_KIND_SVE_*, the SVE
// immediates and memory, and the options of the SVE schemes). isSveSpec()
// tells whether a spec is one of them, so ArmOperandCodec::decode / encode
// dispatch to these functions
bool isSveSpec(const ArmOperandSpec& spec);
bool decodeSve(const ArmOperandSpec& spec,
               uint32 encoding,
               const ArmCodecContext& context,
               ArmDecodedOperand& operand);
bool encodeSve(const ArmOperandSpec& spec,
               const ArmDecodedOperand& operand,
               const ArmCodecContext& context,
               uint32& encoding);
// The names of the SVE option schemes (ARM_OPT_SVE_*): the formatter and the
// parser find them through getOptionName / findOption
const char* getSveOptionName(uint scheme, uint value);
bool findSveOption(uint scheme, const cString& name, uint& value);

// ArmOperandCodecSme.cpp: the SME kinds (ARM_KIND_SME_*: the za tiles, slices
// and arrays, the tile list of zero, zt0, the indexed z registers and the
// memory of ldr za). isSmeSpec() tells whether a spec is one of them
bool isSmeSpec(const ArmOperandSpec& spec);
bool decodeSme(const ArmOperandSpec& spec,
               uint32 encoding,
               const ArmCodecContext& context,
               ArmDecodedOperand& operand);
bool encodeSme(const ArmOperandSpec& spec,
               const ArmDecodedOperand& operand,
               const ArmCodecContext& context,
               uint32& encoding);

/*
 * The names of the option values and of the system registers. Generated by
 * tests/arm/tools/gen_a64_names.py from the LLVM tables (Arm64Names.cpp)
 */
struct ArmNamedValue {
    uint16 m_value;
    // ARM_NAME_* bits
    uint8 m_flags;
    // The name as LLVM prints it (case insensitive for the parser). NULL ends
    // a table
    const char* m_name;
};
enum {
    // The sys alias takes no register (ic ialluis): its Rt field is ignored
    ARM_NAME_NO_REGISTER = 1
};

// Return true if the sys alias with the given option value takes a register
// (a name of the scheme which has no ARM_NAME_NO_REGISTER)
bool optionTakesRegister(uint scheme, uint value);
// The names of each ArmOptionScheme. The pointer is NULL if the scheme has
// no names
extern const ArmNamedValue* const gArmOptionNames[ARM_OPT_SCHEMES_COUNT];

// A system register: m_packed is op0:op1:CRn:CRm:op2 (16 bits, the
// instruction bits 5-20), m_access the ARM_SYSREG_* bits
enum {
    ARM_SYSREG_READ  = 1,
    ARM_SYSREG_WRITE = 2
};
struct ArmSystemRegisterName {
    uint16 m_packed;
    uint8 m_access;
    // The name as LLVM prints it (uppercase)
    const char* m_name;
};
// Sorted by m_packed
extern const ArmSystemRegisterName gArmSystemRegisters[];
extern const uint gArmSystemRegistersCount;

/*
 * Helpers shared by the areas
 */
// Return the number of a name followed by decimal digits: "x12" with the
// prefix "x" gives 12. False if the name isn't the prefix and 'maximum' or
// less (no leading zeros)
bool parseNumberedName(const cString& name, const char* prefix, uint maximum,
                       uint& number);

// Return the absolute address which an operand of a branch or a pc relative
// instruction names (KIND_BRANCH_TARGET, or KIND_IMMEDIATE: an offset from the
// instruction when it was written with a '#', an address otherwise).
// False for the other operands
bool getBranchTarget(const ArmDecodedOperand& operand,
                     const ArmCodecContext& context,
                     uint64& target);

// Decode the N, immr and imms of an A64 bitmask immediate for a register of
// 'size' bits (32 or 64). False for the reserved encodings
bool decodeLogicalImmediateValue(uint n, uint immr, uint imms, uint size, uint64& value);

// Sign extend 'value' of 'width' bits
int64 signExtend(uint64 value, uint width);

// Return the text of a number in hexadecimal, lowercase, without a prefix
cString hexText(uint64 value);

} // namespace armdis

#endif // __TBA_DISMOUNT_PROC_ARM_ARMOPERANDCODECINTERNAL_H
